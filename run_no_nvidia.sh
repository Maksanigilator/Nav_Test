#!/usr/bin/env bash
# Запуск стека на машине БЕЗ видеокарты NVIDIA.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ АВТООПРЕДЕЛЕНИЕ. Чтобы выбор был явным и
# видимым. С автоопределением непонятно, что произошло: карты нет, или
# она есть, но не подхватилась, — а сообщение докера "could not select
# device driver" одинаково в обоих случаях. Здесь же из имени команды
# сразу ясно, что запущено.
#
# ВСЯ ЛОГИКА ОСТАЁТСЯ В run.sh. Копировать его сюда нельзя: там около
# двухсот строк про --ipc host, правила device-cgroup, X-cookie и
# транспорт Fast DDS, и копия неминуемо разошлась бы с оригиналом при
# первой же правке. Здесь только флаг.
#
# Что меняется в run.sh при NO_NVIDIA=1:
#   * не передаётся --gpus all (иначе докер откажет и контейнер не встанет);
#   * не задаются переменные NVIDIA для OpenGL;
#   * RViz идёт через Mesa и /dev/dri — на встроенной видеокарте этого
#     достаточно, ничего доустанавливать не нужно.
#
# Весь навигационный стек считается на процессоре: визуальная одометрия
# RTAB-Map, Nav2, MPPI, детектор обрыва. Видеокарта нужна только ело.
set -euo pipefail
echo "Запуск БЕЗ NVIDIA: OpenGL через Mesa, --gpus не передаётся."
NO_NVIDIA=1 exec "$(cd -- "$(dirname -- "$(readlink -f -- "${BASH_SOURCE[0]}")")" && pwd -P)/run.sh" "$@"
