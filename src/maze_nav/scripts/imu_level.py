#!/usr/bin/env python3
"""Меряет, НАСКОЛЬКО КРИВО привинчена плата ИНС, и выдаёт поправку для URDF.

ЗАЧЕМ. Неподвижный акселерометр меряет направление «вверх». Если плата
стоит ровно, а робот — на ровном полу, вектор обязан быть (0, 0, +9.81).
Всякое отклонение и есть перекос крепления.

Ошибка эта коварная: она ПОСТОЯННАЯ и потому не выглядит ошибкой. Узел
одометрии берёт из ИНС начальную ориентацию по гравитации
(wait_imu_to_init), и перекос уезжает в сам кадр odom. После этого
наклонённым оказывается ВСЁ, что размещается по позе робота: карта,
облако, слой рельсов, модель робота в RViz. Замерено на стенде: 1.65
градуса перекоса плюс уход одометрии давали 3.4 градуса суммарно, то есть
12 см перепада на двух метрах.

ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ДВУХ ДРУГИХ ПОМОЩНИКОВ

* `imu_axes.py` — грубая перестановка осей, какая ось датчика куда смотрит.
  Результат идёт в параметр `axes` узла. Двадцать четыре варианта, выбор
  дискретный.
* `imu_bias.py` — смещение нуля, то есть что датчик показывает в покое
  вместо нуля. Результат идёт в параметры `gyro_bias` и `accel_bias`.
* Этот — непрерывный наклон крепления, единицы градусов. Результат идёт
  в URDF, потому что это утверждение о ГЕОМЕТРИИ робота, а не о данных.

ПОЧЕМУ В URDF, А НЕ ПОВОРОТОМ ВЕКТОРОВ В УЗЛЕ. Перекос — физический факт
о том, как плата привинчена. URDF для того и нужен, чтобы такие факты
описывать, и тогда поправку получают все потребители разом: RTAB-Map
берёт преобразование от кадра ИНС к базе через TF и разворачивает данные
сам. Крутить векторы внутри узла значило бы подменять показания, чтобы
компенсировать неверный URDF, и через месяц никто не вспомнит почему.

ЧТО НУЖНО ДЛЯ ЗАМЕРА. Робот стоит НЕПОДВИЖНО на ровной поверхности.
Замер смешивает перекос платы с уклоном пола и развести их не может —
но нам и нужно именно совмещение робота с вертикалью на той поверхности,
по которой он ездит.
"""
import math
import sys

import numpy as np
import rclpy
from rclpy.node import Node
from rclpy.qos import QoSPresetProfiles
from sensor_msgs.msg import Imu

G = 9.80665


class Level(Node):
    def __init__(self):
        super().__init__('imu_level')
        self.declare_parameter('topic', '/imu/data_raw')
        self.declare_parameter('samples', 600)
        # Порог неподвижности: если за время замера разброс больше, робот
        # шевелился и числам верить нельзя.
        self.declare_parameter('still_tol', 0.25)
        self.buf = []
        self.create_subscription(
            Imu, str(self.get_parameter('topic').value), self.on_imu,
            QoSPresetProfiles.SENSOR_DATA.value)

    def on_imu(self, m):
        a = m.linear_acceleration
        self.buf.append((a.x, a.y, a.z))


def main():
    rclpy.init()
    n = Level()
    want = int(n.get_parameter('samples').value)
    print(f'\nРобот должен стоять НЕПОДВИЖНО. Набираю {want} выборок...')
    try:
        while len(n.buf) < want and rclpy.ok():
            rclpy.spin_once(n, timeout_sec=0.2)
    except KeyboardInterrupt:
        pass
    if len(n.buf) < 20:
        print('\nДанных нет. Запущен ли узел ИНС и тот ли топик?')
        return 1

    A = np.array(n.buf)
    v = A.mean(axis=0)
    g = float(np.linalg.norm(v))
    spread = float(np.linalg.norm(A.std(axis=0)))
    print(f'\nускорение  X{v[0]:+.3f}  Y{v[1]:+.3f}  Z{v[2]:+.3f}   '
          f'|a| = {g:.3f} м/с²')
    print(f'разброс за замер {spread:.3f} м/с² '
          f'({"стоял спокойно" if spread < float(n.get_parameter("still_tol").value) else "ШЕВЕЛИЛСЯ, повтори"})')

    if abs(g - G) > 1.5:
        # Величина на наклон не влияет — он считается по НАПРАВЛЕНИЮ, —
        # но расхождение означает неверную шкалу, и это отдельная беда.
        print(f'\n  Внимание: |a| далеко от {G:.2f}. Направление от этого не '
              f'страдает,\n  но шкала акселерометра задана неверно: похоже, '
              f'узел и прошивка\n  разошлись в диапазоне. Отношение '
              f'{G / g:.2f} подсказывает множитель.')

    if v[2] <= 0:
        print('\n  Z смотрит вниз. Сначала разберись с осями: imu_axes.py')
        return 1

    u = v / g
    # Крен и тангаж, совмещающие измеренную вертикаль с осью Z.
    # Знаки выбраны так, чтобы поворот на эти углы делал вектор (0,0,1).
    roll = math.atan2(u[1], u[2])
    pitch = math.atan2(-u[0], math.hypot(u[1], u[2]))
    tilt = math.degrees(math.acos(min(1.0, u[2])))

    # Проверяем сами себя: применяем найденный поворот и смотрим остаток.
    cr, sr = math.cos(roll), math.sin(roll)
    cp, sp = math.cos(pitch), math.sin(pitch)
    Rx = np.array([[1, 0, 0], [0, cr, -sr], [0, sr, cr]])
    Ry = np.array([[cp, 0, sp], [0, 1, 0], [-sp, 0, cp]])
    out = Ry @ Rx @ u
    left = math.degrees(math.acos(min(1.0, float(out[2]))))

    print(f'\nперекос крепления: {tilt:.2f}°')
    print(f'  крен  {math.degrees(roll):+.2f}°')
    print(f'  тангаж {math.degrees(pitch):+.2f}°')
    print(f'  остаток после поправки: {left:.3f}° '
          f'({"хорошо" if left < 0.05 else "подозрительно много"})')

    if tilt < 0.3:
        print('\nПлата стоит ровно, править URDF незачем.')
        return 0

    print('\nВ URDF, в стык imu_joint, добавить поворот:')
    print(f'\n    <origin rpy="{roll:.5f} {pitch:.5f} 0"/>\n')
    print('Знак такой, чтобы поворот ПРИВОДИЛ измеренную вертикаль к оси Z.')
    print('Проверка после правки: запусти этот помощник снова — перекос')
    print('должен стать меньше 0.3°. Если он вырос вдвое, знак обратный.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
