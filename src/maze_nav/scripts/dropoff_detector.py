#!/usr/bin/env python3
"""Детектор обрыва: находит край платформы по глубине и выдаёт его
костмапу под видом обычного препятствия.

    ros2 run maze_nav dropoff_detector.py

Зачем подделка. Ни Nav2, ни RTAB-Map отрицательных препятствий не знают:
в их модели мира препятствие — это то, что торчит ВВЕРХ, а всё, что ниже
порога пола, считается свободным местом. Поэтому обрыв за кромкой настила
размечается как ровная площадка, и планировщик спокойно ведёт туда робота.

Обойти это можно, не трогая Nav2: найти клетки обрыва и опубликовать их
облаком точек НА ВЫСОТЕ. Дальше всё работает само — костмап их пометит,
инфляция раздуется, планировщик обойдёт.

Признаков обрыва два, и настоящий край даёт оба сразу:

1. ТОЧКИ НИЖЕ ОПОРНОЙ ПЛОСКОСТИ. Пол за кромкой лежит на 120 мм ниже
   настила. Это не отсутствие данных, а положительное измерение, и оно
   даёт метрическое положение.

2. ТЕНЬ ЗА КРОМКОЙ. Сразу за краем есть полоса, куда не попадает ни один
   луч — её загораживает сама кромка. Ширина считается точно:
       тень = высота обрыва * расстояние / высота камеры
   При кромке в метре впереди и камере на 0.72 м это 17 см пустоты.

Второй признак здесь используется как проверка: шум дальномера даёт
одиночные точки ниже плоскости где угодно, но тени за собой не оставляет.
Поэтому одиночные срабатывания отсеиваются требованием, чтобы рядом были
соседи (минимальный размер пятна).
"""
import math

import cv2
import numpy as np
import rclpy
import rclpy.duration
import sensor_msgs_py.point_cloud2 as pc2
import tf2_ros
from rclpy.node import Node
from rclpy.qos import QoSProfile, ReliabilityPolicy
from rtabmap_msgs.msg import MapData, MapGraph
from sensor_msgs.msg import CameraInfo, Image, PointCloud2, PointField
from rclpy.qos import DurabilityPolicy
from geometry_msgs.msg import PoseStamped
from std_msgs.msg import Header
from visualization_msgs.msg import Marker, MarkerArray


class DropoffDetector(Node):
    def __init__(self):
        super().__init__('dropoff_detector')
        self.declare_parameter('base_frame', 'base_footprint')
        # Ниже этой отметки относительно опорной плоскости — обрыв.
        # 60 мм: половина высоты настила. Меньше — ловим шум дальномера,
        # больше — обрыв обнаруживается слишком поздно.
        self.declare_parameter('drop_threshold', -0.06)
        # На какой высоте публиковать подделку. Выше порога пола костмапа
        # и ниже габарита робота, чтобы слой точно её принял.
        self.declare_parameter('virtual_height', 0.30)
        self.declare_parameter('max_range', 3.0)
        # ── Опорная плоскость: из данных, а не из URDF ──
        #
        # Исходно плоскостью служил z=0 кадра base_footprint, то есть
        # положение камеры целиком бралось из URDF. В симуляторе URDF и
        # есть истина, и это работало. На живом роботе камеру крепят
        # руками: замерено на стенде — в URDF записан наклон 45 градусов,
        # а фактический оказался около 50, и этих пяти градусов хватило,
        # чтобы настил высотой 10 см лёг на -1 см вместо -10 и не прошёл
        # порог обрыва. Детектор при этом молчал совершенно исправно:
        # точки были, перелёта не было.
        #
        # Поэтому плоскость подгоняем по ближней земле под роботом в
        # каждом кадре. Это снимает заодно и крен от подвески, который
        # при камере на крыше даёт на двух метрах те же сантиметры.
        #
        # ЭТО ВРЕМЕННАЯ МЕРА. Камера сейчас стоит на подвижном штативе с
        # фиксацией, и угол выставлен на глаз, отсюда и нужда мерить его
        # по данным. Когда её переставят на жёсткое крепление, угол надо
        # будет измерить один раз и записать в URDF (параметр --cam-pitch
        # у gen_robot_urdf.py), а подгонку выключить: у неё собственная
        # ошибка около градуса, а у точного числа в файле — никакой.
        self.declare_parameter('ground_fit', True)
        # Радиус участка под роботом, по которому подгоняем. Должен быть
        # заведомо меньше расстояния до кромки, иначе в оценку попадёт
        # нижний уровень и плоскость наклонится к нему.
        self.declare_parameter('ground_fit_range', 1.1)
        # Насколько далеко от плоскости URDF ещё ищем землю.
        self.declare_parameter('ground_fit_band', 0.25)
        # Предохранитель: поправка больше этой — значит подгонка села на
        # что-то, что землёй не является, и лучше остаться на URDF.
        self.declare_parameter('ground_fit_max_tilt', 15.0)
        self.declare_parameter('ground_fit_max_shift', 0.30)
        # Сколько измерений плоскости усреднять. Поправка — это КАЛИБРОВКА
        # крепления камеры, величина постоянная, а не сиюминутная. Пока она
        # применялась покадрово, её дрожание (замерено: 2.4, 2.6, 2.8, 1.2,
        # 0.8 градуса подряд) уходило в карту: каждый кадр клал рельсы под
        # своим углом, а слой липкий и стереть ничего нельзя — накопленные
        # трубы размазывались в клин. Медиана за полторы сотни кадров (на
        # 30 Гц это пять секунд) дрожание убирает, а настоящий перекос
        # крепления находит ничуть не хуже: он никуда не девается.
        self.declare_parameter('ground_fit_samples', 150)
        # Дальность облака, уходящего в сетку занятости. Меньше общей
        # намеренно: порог сетки «выше пола» постоянный, 30 мм, а шум
        # дальномера растёт как квадрат дальности и на трёх метрах даёт
        # те же 30 мм. Каждая вторая клетка на дальней границе обзора
        # перещёлкивается в препятствие, и по краю карты вырастает кайма
        # ложных препятствий, похожая на рельсы.
        # На 2.0 м сигма 13 мм — порог отстоит на 2.3 сигмы, ложных около
        # процента. Потеря охвата не страшна: робот едет и накапливает.
        self.declare_parameter('grid_max_range', 2.0)
        # Сторона клетки, по которой берём медиану высоты. 5 см заметно
        # меньше трубы Ø51 мм, так что рельс клетку не теряет.
        self.declare_parameter('grid_cell', 0.05)
        # Пятачок под роботом, который считаем свободным по построению.
        # Размер колёсного прямоугольника: полубаза 0.3178 и полуколея
        # 0.3554 м по обмеру CAD.
        self.declare_parameter('free_patch_length', 0.636)
        self.declare_parameter('free_patch_width', 0.711)
        # Насколько отодвигать точки пола от рельса, чтобы они не попали с
        # ним в одну клетку сетки и не размыли его цвет.
        # 10 см, а не 6: карта копится по кадрам, клетка сетки RTAB-Map
        # равна 5 см, и её сетка смещена относительно нашей, поэтому точка
        # пола с соседнего кадра всё равно попадала к рельсу в один воксель
        # и перебивала цвет. Замерено: при 6 см на рельсах оставалось 14
        # серых точек против 19 зелёных.
        self.declare_parameter('rail_clear_cell', 0.10)
        # Сколько масок держать для сопоставления по времени. Десяти
        # хватает: при 10 Гц это секунда истории, а маска старше допуска
        # всё равно отбрасывается.
        self.declare_parameter('mask_buffer', 10)
        # Предельное расхождение маски и кадра глубины. 120 мс — это чуть
        # больше периода модели на 10 Гц, то есть соседний кадр ещё
        # годится, а пропуск уже нет.
        self.declare_parameter('mask_max_age', 0.12)

        # ── Накопитель рельсов ──
        #
        # Рельсы ведутся СВОИМ слоем, отдельно от карты RTAB-Map, и вот
        # почему так, а не закраской её вокселей. Карта не хранится как
        # набор вокселей: она хранится графом узлов, у каждого своё облако
        # в собственных координатах, а то, что видно в RViz, — пересборка
        # этих облаков по текущим позам узлов. При замыкании петли позы
        # прошлых узлов сдвигаются, сборка делается заново, и закраска
        # поверх неё была бы затёрта.
        #
        # Отдельный слой заодно снимает требование синхронизации: узнать,
        # какие кадры RTAB-Map взял ключевыми, нельзя — он решает это внутри
        # себя. Своему слою это и не нужно, ему хватает пары «маска и
        # глубина с одной меткой» плюс TF на этот момент.
        #
        # ЛИПКОСТЬ. Помеченная клетка не снимается никогда. Посылка в том,
        # что сегментация ошибается только в ненахождении, но не в ложном
        # срабатывании: труба, увиденная хоть раз, там и есть, а не
        # увиденная на следующем кадре — просто не распозналась. Поэтому
        # наблюдения складываются, и частичная видимость лечится сама:
        # не разглядели трубу с одного ракурса — разглядим с другого.
        #
        # ИЗВЕСТНЫЙ ИЗЪЯН: СЛОЙ ПОПЛЫВЁТ ОТНОСИТЕЛЬНО КАРТЫ. Точки
        # кладутся в координаты map по TF НА МОМЕНТ СЪЁМКИ. При замыкании
        # петли RTAB-Map сдвигает позы прошлых узлов и перестраивает
        # карту, а уже положенные нами точки остаются на месте. На стенде
        # 2x2 м с короткими проездами это доли сантиметра, на длинном
        # маршруте по теплице — нет.
        #
        # Правильное лечение — хранить наблюдения привязанными к ключевым
        # кадрам и пересобирать слой при изменении графа, то есть делать
        # то же, что делает RTAB-Map. Это заметно дороже и сейчас отложено
        # осознанно. Если слой начнёт расходиться с картой на глаз —
        # причина здесь, а не в сегментации.
        self.declare_parameter('rail_accumulate', True)
        # СЖАТИЕ МАСКИ ПЕРЕД НАКОПЛЕНИЕМ, в пикселях от края.
        #
        # На границе объекта стереопара даёт точки-призраки (flying
        # pixels): окно сопоставления захватывает и трубу, и пол за ней,
        # пик корреляции садится между двумя диспаратностями, и точка
        # материализуется НА ОТРЕЗКЕ между ближней и дальней поверхностью.
        # В облаке это видно диагональными тяжами от труб к настилу.
        #
        # Опаснее обычного шума они двумя свойствами: систематические
        # (всегда между двумя поверхностями) и односторонние (со стороны
        # затенения). Робастное ядро в подгонке их не давит — Коши
        # рассчитан на СЛУЧАЙНЫЕ выбросы, а эти смещают оценку согласованно.
        #
        # Платим настоящими точками силуэта, и платим дёшево: фигура
        # вписывается с ИЗВЕСТНОЙ колеёй и диаметром трубы, так что потеря
        # краевых точек почти ничего не стоит, а примесь ложных смещает
        # угол. Эталон для проверки есть: колея 526 мм, детектор печатает
        # измеренную в каждом кадре.
        #
        # 0 — выключить.
        self.declare_parameter('rail_mask_erode', 5)
        # КАДР СЛОЯ: odom, А НЕ map — и это не опечатка.
        #
        # Казалось бы, накопленному слою место в карте: она же и есть
        # глобальная система отсчёта. Но замерено на стоящем роботе:
        #
        #     одометрия odom->base : углы размах 0.17-0.23 градуса
        #     карта     map->odom  : крен 1.58, тангаж 1.10 градуса
        #
        # Карту к вертикали привязывает RTAB-Map по ИНС, а ориентация с
        # ИНС сама гуляет на 2.4-3.7 градуса (магнитометра нет, курс вовсе
        # не определён). Эта дрожь целиком переходит в map->odom.
        #
        # Для липкого слоя это губительно: качание на полтора градуса
        # возит точку на двух метрах на 5 см, а слой сохраняет КАЖДУЮ
        # копию. Наружу это выглядело как «рельсы съезжают» — несколько
        # смещённых пластов зелёного вместо двух ниток.
        #
        # Одометрия же гладкая. Она уходит со временем, но заезд длится
        # минуту-две на нескольких метрах, и её уход за это время заведомо
        # меньше нынешнего качания карты.
        #
        # ЧЕМ ПЛАТИМ: слой перестаёт переживать замыкания петли идлинные
        # маршруты. Для заезда это неважно, для долгой работы по теплице —
        # важно, и тогда надо возвращаться в map, но сперва унять ИНС.
        #
        # Потребитель обязан брать кадр ИЗ ЗАГОЛОВКА облака, а не
        # предполагать его: rail_entry.py так и делает.
        self.declare_parameter('rail_map_frame', 'odom')
        # Шаг решётки СЛОЯ РЕЛЬСОВ. Мельче, чем у сетки занятости.
        #
        # Труба 51 мм в клетке 5 см занимает одну-две клетки, и понять по
        # такой картинке, где рельс проходит на самом деле, нельзя —
        # положение округлено до половины трубы. При 2.5 см труба это уже
        # две-три клетки, и нитка читается.
        #
        # Мельчить ОБЩУЮ сетку при этом нельзя, и это не из экономии:
        # укрупнение и есть то, чем гасится шум дальномера. Медиана по
        # клетке 5 см срезает дрожание, а в мелкой клетке точек мало и
        # шум возвращается — на дальнем краю обзора это давало зелёную
        # сыпь из ложных препятствий.
        #
        # Слою рельсов мельчить можно, потому что у него своя защита от
        # шума, не связанная с размером клетки: клетка принимается только
        # после нескольких подтверждений (rail_min_hits). Случайная точка
        # до них не доживает независимо от того, крупная клетка или мелкая.
        #
        # Цена: клеток становится вчетверо больше, и на каждую приходится
        # меньше попаданий. Если доля подтверждённых в отчёте заметно
        # упадёт, снижать rail_min_hits до двух.
        self.declare_parameter('rail_voxel', 0.025)
        # Дальше этого рельсы в слой не берём: шум дальномера растёт как
        # квадрат дальности, а липкая пометка ошибку уже не исправит.
        self.declare_parameter('rail_max_range', 2.5)
        # ── Полоса высот, в которой рельс вообще может быть ──
        #
        # Рельс лежит на той же поверхности, по которой едет робот. Всё,
        # что сегментация пометила заметно выше, рельсом быть не может по
        # устройству стенда.
        #
        # Защита понадобилась не от придирчивости. Чтобы модель вообще
        # заработала на картинке из Gazebo, порог уверенности пришлось
        # опустить с 0.35 до 0.05, а это размен пропусков на ложные
        # срабатывания. И они немедленно появились: замерено — слой
        # набирал точки на высоте от -0.12 до +1.02 м, причём верхний ком
        # оказался КУСКОМ ПОТОЛКА, похожим на трубу. Вписывание колеи по
        # такой смеси давало 206 мм вместо настоящих 545.
        #
        # Это чинит и слабое место самого замысла. Слой липкий, потому что
        # мы условились считать ошибки сегментации только пропусками. При
        # низком пороге условие перестаёт выполняться, а липкость делает
        # каждое ложное срабатывание вечным. Полоса высот возвращает
        # посылку в силу: мимо труб ещё можно промахнуться, но потолок в
        # неё не попадёт никогда.
        #
        # Границы заданы в кадре робота, где земля под ним — нуль.
        #
        # НИЖНЯЯ ГРАНИЦА ВЫШЕ НУЛЯ, и это главное. Рельс ЛЕЖИТ на
        # поверхности, то есть его точки приподняты над ней на высоту
        # трубы. Пол же находится ровно на нуле. Поэтому отсечка «выше
        # земли на 2 см» разделяет их физически, а не по порогу уверенности
        # модели.
        #
        # Понадобилось это после прогона, где маска сползла на пол и слой
        # набрал объёмный ком вместо двух ниток: полосы от -0.20 до +0.35 м
        # для разделения не хватало, в неё попадал и пол.
        #
        # Верхняя граница 12 см: труба 51 мм, настил 10 см, так что всё
        # выше — заведомо не рельс.
        self.declare_parameter('rail_z_min', 0.02)
        self.declare_parameter('rail_z_max', 0.12)
        # СКОЛЬКО РАЗ НАДО УВИДЕТЬ КЛЕТКУ, ЧТОБЫ ЕЙ ПОВЕРИТЬ.
        #
        # Липкость задумывалась от ПРОПУСКОВ сегментации: труба, увиденная
        # хоть раз, там и есть. Но у посылки есть изнанка — ложное
        # срабатывание попадает в слой так же прочно, как настоящая труба,
        # и стереть его нечем. Наблюдалось: вместо двух ниток накапливалось
        # несколько параллельных пластов.
        #
        # Лечим не подгонкой модели, а требованием улик. Ошибки ложатся
        # каждый раз в РАЗНЫЕ клетки, а рельсы стоят на одном месте, и за
        # несколько кадров набирают подтверждения. Модели при этом не
        # предполагается никакой — только повторяемость.
        #
        # Три попадания при сегментации 2 Гц это полторы секунды для
        # неподвижного робота. На ходу участок, мелькнувший однократно, в
        # слой не попадёт — это сознательная плата за чистоту.
        self.declare_parameter('rail_min_hits', 3)
        # ПРИВЯЗКА СЛОЯ К ГРАФУ RTAB-MAP.
        #
        # Без неё слой копится в мировых клетках кадра odom и не
        # поправляется никогда: клетка говорит «рельс в точке odom (x, y)»,
        # а это утверждение протухает вместе с дрейфом одометрии. Хуже
        # того, при сбросе одометрии (Odom/ResetCountdown в запуске)
        # кадр обнуляется, и весь слой становится неверным СКАЧКОМ, без
        # всякого признака.
        #
        # С привязкой наблюдение хранится относительно УЗЛА графа: «рельс
        # в 1.2 м от того места, где я стоял на узле 47». Это верно
        # всегда. Когда граф решит, что узел 47 был в другом месте, рельс
        # уедет вместе с ним — правильно. Узел пропал из графа (сброс,
        # уход в долговременную память) — его точки просто не рисуются,
        # но и не выбрасываются: вернётся узел, вернутся и они.
        #
        # false — прежнее поведение, слой в odom. Откат на случай, если
        # граф окажется недоступен или поведёт себя не так.
        self.declare_parameter('rail_graph_bind', True)
        # Наибольшее расхождение метки наблюдения с меткой узла. Узлы
        # создаются в темпе Rtabmap/DetectionRate (2 Гц), маски приходят
        # тоже 2 Гц, так что пара обычно находится в пределах четверти
        # секунды.
        self.declare_parameter('rail_node_tol', 0.5)
        # ── Модель рельсов: ТОЛЬКО ДЛЯ ГЛАЗ ──
        #
        # Отдельный топик с геометрической фигурой, вписанной в
        # накопленные клетки. В логику заезда НЕ входит: тот по-прежнему
        # работает с самими клетками. Нужна, чтобы глазами сверить, совпал
        # ли найденный рельс с настоящим, — на фоне текстурной карты это
        # видно сразу, а по числам нет.
        #
        # Размеры берутся ИЗВЕСТНЫЕ, а не подгоняются. Здесь обмер
        # НАСТОЯЩИХ рельсов: просвет между боками труб 470 мм, труба 56 мм,
        # значит колея по осям 470 + 56 = 526 мм.
        #
        # В сцене симулятора (gen_rails_world.py) числа ДРУГИЕ — 545 и 51.
        # Они оттуда и пришли когда-то в эти параметры. Сцену не трогаем,
        # но запуск в симуляторе должен задавать свои размеры явно, иначе
        # модель будет меряться реальной колеёй по нарисованным рельсам.
        #
        # Радиус загиба 145 мм НЕ измерен, это оценка на глаз. Ноль
        # выключает отрисовку загиба целиком: выдуманная дуга мешает
        # судить о том, попало ли вписывание.
        # Из данных берётся только НАПРАВЛЕНИЕ и ПОЛОЖЕНИЕ оси — в этом и
        # смысл проверки: модель с верными размерами либо ложится на
        # клетки, либо нет.
        self.declare_parameter('rail_model', True)
        self.declare_parameter('rail_gauge', 0.526)
        self.declare_parameter('rail_pipe_d', 0.056)
        # Радиус загиба 110 мм — ИЗМЕРЕН по накопленному слою, а не взят
        # из сцены симулятора (там 145). Мерено по профилю ширины фигуры:
        # на срезах вдоль оси от кончика П ширина росла 469, 525, 598 и
        # дальше стояла на 600 мм. Выход на полку и есть конец дуги, то
        # есть её радиус — около 110 мм.
        #
        # Способ через длину перемычки (R = (колея - перемычка)/2) здесь
        # НЕ работает: множество «между трубами» обрезано порогом
        # half - tol = 215 мм, перемычка длиннее 430 мм в него не влезает,
        # и оценка упирается в потолок. Давало 63 мм, то есть вдвое мимо.
        self.declare_parameter('rail_bend_r', 0.110)
        # Допуск подгонки СВЕРХ радиуса трубы. Клетка 25 мм, маска по
        # краям рыхлая, поэтому полоса вокруг оси трубы берётся шире
        # самой трубы: 28 мм радиуса плюс 20 допуска.
        self.declare_parameter('rail_fit_tol', 0.020)
        # Шаг перебора по углу. Полградуса на полутора метрах длины дают
        # 13 мм на конце — меньше половины клетки, мельче незачем.
        self.declare_parameter('rail_fit_angle_step', 0.5)
        self.declare_parameter('rail_fit_iters', 12)
        self.declare_parameter('rail_publish_period', 0.5)
        # Сколько кадров глубины держать, чтобы дождаться маску на них.
        # Круговая задержка замерена в 11-20 мс, но модель может идти
        # реже кадров, поэтому запас в полсекунды.
        self.declare_parameter('rail_frames', 20)
        # Допуск на совпадение меток маски и глубины.
        #
        # На реальном роботе они совпадают ТОЧНО: маска несёт header
        # цветного кадра, а глубина выровнена по цвету и несёт его же
        # метку. Поэтому сначала здесь стояло 20 мс.
        #
        # В симуляторе это неверно. Замерено: ближайший кадр глубины
        # отстоит от метки маски ровно на 66 мс, и так каждый раз. Это
        # половина периода кадра (132 мс при 7.6 Гц) — цвет и глубина там
        # идут не одновременно, а вперемежку. С допуском 20 мс накопитель
        # отвергал ВСЕ маски подряд и оставался пустым, хотя сегментация
        # работала и покадровая раскраска рельсы находила.
        #
        # 80 мс берут соседний кадр и отвергают пропущенный. На скорости
        # 0.3 м/с это 2 см промаха — меньше клетки решётки.
        self.declare_parameter('rail_pair_tol', 0.08)
        # Прореживание: считать каждый N-й пиксель.
        # Каждый второй пиксель, а не каждый четвёртый. На четвёртом
        # труба 51 мм с двух метров занимает единицы отсчётов и теряется:
        # замерено — рельсы пропадали с карты, оставались точки.
        self.declare_parameter('step', 2)
        self.declare_parameter('min_cluster', 3)
        # Сколько строк подряд должен держаться перелёт, чтобы считать его
        # краем. Щель 4 мм в кадре занимает один-два отсчёта и отсеивается.
        self.declare_parameter('min_run', 8)
        # Порог перелёта идёт от ШУМА ДАЛЬНОМЕРА, а не от высоты ступеньки.
        #
        # Перелёт за кромкой равен h/sin(угол склонения), и у самого края
        # угол крутой, а перелёт МАЛЕНЬКИЙ: при ступеньке 120 мм и кромке
        # в 1.1 м это 0.22 м, а в 2.2 м — уже 0.40 м. Поэтому постоянный
        # порог в метрах отодвигает детектор наружу: он ждёт, пока перелёт
        # дорастёт. Проверено — с порогом 0.25 м кромка определялась на
        # 2.24 м вместо 1.10.
        #
        # У D435 шум растёт как квадрат дальности (он задан в
        # диспаратности), поэтому порог берём таким же: три сигмы шума.
        self.declare_parameter('overshoot_k', 0.010)     # ~3 сигмы, м на м^2
        self.declare_parameter('overshoot_min', 0.03)
        # Кромку ищем только вблизи: дальше пол виден под слишком острым
        # углом, чтобы верить его высоте.
        self.declare_parameter('edge_max_range', 2.5)
        # Сглаживание по времени: медиана дальности кромки в каждом столбце
        # за последние N кадров. Одиночный выброс шума медиану не сдвинет,
        # а настоящая кромка стоит на месте.
        self.declare_parameter('smooth_frames', 5)
        # Окно медианы поперёк столбцов кадра, против отростков на рельсах.
        self.declare_parameter('cross_median', 9)
        # Сколько столбцов подряд без наблюдения ещё разрешено закрыть
        # интерполяцией. 20 из 320 — это около 24 см кромки на двух метрах.
        self.declare_parameter('edge_gap_fill', 20)
        # Сколько строк недолёта достаточно, чтобы счесть столбец занятым
        # предметом. Труба 51 мм с полутора метров занимает не одну строку.
        self.declare_parameter('block_rows', 3)
        # Радиус зоны без кромки вокруг предмета, в метрах. Нужен, чтобы
        # робот мог отъехать назад после неудачного заезда и не упёрся в
        # собственную разметку у рельсов.
        self.declare_parameter('block_radius', 0.30)

        # Высоту рельса меряем над МЕСТНЫМ минимумом, а не над опорной
        # плоскостью. Причина: пол двухуровневый. На настиле рельс торчит
        # на +51 мм, а за кромкой он стоит на нижнем полу и оказывается на
        # 69 мм НИЖЕ плоскости настила. Единой высоты у него нет вовсе,
        # а над соседним полом он всегда на свои 51 мм.
        # Окно для местного минимума. Больше клетки намеренно: труба 51 мм
        # влезает в клетку 5 см целиком, и пола рядом не остаётся — минимум
        # получился бы по самой трубе, и рельс стал бы невидим.
        # Дальше 1.8 м отношение высоты трубы к шуму падает ниже пяти, и
        # кандидатов от шума пола становится больше, чем от рельсов —
        # вписывание начинает цепляться за случайные скопления. Замерено:
        # на 2.5 м курс прыгал между -38° и +35° от кадра к кадру.
        # Для заезда дальше и не нужно: выравниваемся с 1.0-1.5 м.
        # Колея по осям труб — измерена по стенду, см. gen_rails_world.py.
        # Кандидатов рядом с кромкой выбрасываем. У края окно для уровня
        # пола захватывает нижний уровень, и полоса точек прямо по кромке
        # читается приподнятой — получается длинная прямая, которую
        # вписывание принимает за рельс. Замерено: находило курс 86° и
        # смещение 1.08 м, то есть ровно кромку настила.
        # Сглаживание оценки по кадрам: одиночный промах вписывания
        # медиану не сдвинет, а рельсы стоят на месте.
        self._hist = []

        self.base = self.get_parameter('base_frame').value
        self.k = None
        self.buf = tf2_ros.Buffer()
        self.listener = tf2_ros.TransformListener(self.buf, self)

        # ПОДПИСКИ — best effort, как принято для сенсорных данных.
        # Reliable-подписка не принимает сообщения от best-effort издателя
        # вовсе, а узел шума глубины публикует именно best effort. Пока
        # цепочка шла напрямую от моста (он reliable), совпадало случайно;
        # стоило вставить шум — и детектор замолчал, а следом встала карта.
        # Обратное сочетание безопасно: best-effort подписка принимает и от
        # reliable издателя.
        sub_qos = QoSProfile(depth=1, reliability=ReliabilityPolicy.BEST_EFFORT)
        # ПУБЛИКАЦИИ оставляем reliable: их читает RTAB-Map, и такой
        # издатель совместим с подписчиком любого вида.
        qos = QoSProfile(depth=1, reliability=ReliabilityPolicy.RELIABLE)
        self.create_subscription(CameraInfo, 'camera_info', self.on_info, sub_qos)
        self.create_subscription(Image, 'depth', self.on_depth, sub_qos)
        # Граф RTAB-Map. mapGraph несёт позы узлов, но БЕЗ меток времени;
        # метки есть только в mapData. Поэтому нужны оба: по mapData
        # узнаём, какому мгновению соответствует узел, по mapGraph —
        # где этот узел сейчас стоит.
        self.create_subscription(MapGraph, '/mapGraph', self.on_graph, 1)
        self.create_subscription(MapData, '/mapData', self.on_map_data, 1)
        # Маска рельсов из оракула (позже — из модели CV). Без неё детектор
        # работает как раньше, просто все препятствия будут одного цвета.
        # Буфер масок с метками времени, см. on_mask.
        self.masks = []
        # Кадры глубины ждут своей маски: (метка, глубина, R, O).
        # Храним ИМЕННО глубину, а не готовое облако: при прореживании
        # вдвое это 407 КБ на кадр против 1.2 МБ, а поднять нужные точки
        # обратно в 3D стоит доли миллисекунды и только по маске.
        self.frames = []
        # Клетки рельсов: (ix, iy, iz) -> сколько раз увидена. Словарь, а
        # не множество: счётчик нужен, чтобы отличить повторяемое
        # наблюдение от случайного, см. rail_min_hits.
        self.rail_vox = {}
        # Привязка к графу: наблюдения по узлам, позы узлов, метки узлов.
        # obs[id] — свой воксельный словарь В КАДРЕ УЗЛА, со счётчиками.
        # Храним именно словарь, а не список точек: так память ограничена
        # размером сцены, а счётчик попаданий (rail_min_hits) сохраняется.
        self.obs = {}
        self.node_pose = {}             # id -> (R, t) в кадре map
        self.node_stamp = {}            # id -> float, секунды
        self.graph_dirty = False
        self.bound = False              # привязка реально работает
        # Накопленные измерения плоскости, см. ground_fit_samples.
        self._gfit = []
        self.create_subscription(Image, 'rails/mask', self.on_mask, sub_qos)
        self.pub = self.create_publisher(PointCloud2, 'dropoff', qos)
        # Полное облако для сетки занятости: настоящие препятствия как есть,
        # а точки обрыва ПОДНЯТЫ на virtual_height. RTAB-Map строит сетку по
        # нему и размечает обрыв препятствием, ничего не зная про обрывы.
        self.grid = self.create_publisher(PointCloud2, 'grid_cloud', qos)
        # Слой рельсов: тот же PointCloud2 с цветом в точках, что и всё
        # остальное, только решётку строим мы сами и в координатах карты.
        # Поэтому усреднять цвет внутри клетки нечему и затирать зелёное
        # серым нечем — серого в этом слое нет.
        self.rail_pub = self.create_publisher(PointCloud2, 'rails/map', qos)
        # Готовая поза рельсов для автомата заезда. Публикуется
        # ВСЕГДА, независимо от rail_model: модель это картинка, а
        # поза — рабочие данные, и заезд не должен зависеть от того,
        # включена ли у кого-то визуализация.
        self.rail_pose_pub = self.create_publisher(
            PoseStamped, 'rails/pose', qos)
        self.model_pub = self.create_publisher(
            MarkerArray, 'rails/model',
            QoSProfile(depth=1, durability=DurabilityPolicy.TRANSIENT_LOCAL))
        self.create_timer(float(self.get_parameter('rail_publish_period').value),
                          self.publish_rails)
        self.get_logger().info('детектор обрыва запущен')

    def on_info(self, m):
        self.k = (m.k[0], m.k[4], m.k[2], m.k[5])

    def on_mask(self, m):
        """Маску кладём в буфер С МЕТКОЙ, а не поверх предыдущей.

        Раньше здесь хранилась последняя пришедшая маска, и в on_depth она
        бралась к любому кадру глубины, лишь бы совпал размер. Пока маску
        давал оракул на частоте кадров, это сходило с рук. С настоящей
        моделью частота ниже кадровой, и маска относится к КОНКРЕТНОМУ
        снимку: на 10 Гц и скорости 0.3 м/с промах между маской и глубиной
        доходит до 3 см, причём смещение систематическое — всегда назад по
        ходу. Рельс от этого уезжает вбок на карте.
        """
        # Шаг строки не обязан равняться ширине, берём его честно.
        a = np.frombuffer(m.data, np.uint8).reshape(m.height, m.step)
        mask = a[:, :m.width] > 0
        ns = (int(m.header.stamp.sec) * 1_000_000_000
              + int(m.header.stamp.nanosec))
        # В БУФЕР КЛАДЁМ ПОЛНУЮ МАСКУ, А НАКАПЛИВАЕМ СЖАТУЮ.
        #
        # У маски два потребителя с ПРОТИВОПОЛОЖНЫМИ требованиями.
        # Накопитель слоя хочет её скупой: лишний пиксель на краю трубы
        # даёт призрака, а по слою вписывается фигура и считается точка
        # входа. Исключение труб из подгонки земли (mask_for -> rail_sub)
        # хочет ровно обратного — щедрой: пропущенный пиксель трубы
        # заваливает плоскость, замерено 2.7 градуса на заведомо верных
        # данных. Поэтому сжатие идёт ТОЛЬКО в накопитель.
        self.masks.append((ns, mask))
        del self.masks[:-int(self.get_parameter('mask_buffer').value)]
        if bool(self.get_parameter('rail_accumulate').value):
            self.accumulate_rails(self.shrink(mask), ns)

    def shrink(self, mask):
        """Убрать полосу шириной rail_mask_erode пикселей от края маски."""
        r = int(self.get_parameter('rail_mask_erode').value)
        if r <= 0:
            return mask
        k = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * r + 1, 2 * r + 1))
        return cv2.erode(mask.astype(np.uint8), k) > 0

    def mask_for(self, stamp):
        """Маска, ближайшая по времени к кадру глубины, или None.

        Если ближайшая всё равно слишком стара, лучше остаться совсем без
        маски: рельсы тогда просто не покрасятся, тогда как чужая маска
        поставит зелёные клетки мимо труб, а по ним считается точка входа.
        """
        if not self.masks:
            return None
        ns = int(stamp.sec) * 1_000_000_000 + int(stamp.nanosec)
        best_ns, best = min(self.masks, key=lambda it: abs(it[0] - ns))
        age = abs(best_ns - ns) * 1e-9
        if age > float(self.get_parameter('mask_max_age').value):
            self.get_logger().warn(
                f'маска разошлась с кадром на {age * 1000:.0f} мс — не беру',
                throttle_duration_sec=5.0)
            return None
        return best

    def on_depth(self, m):
        if self.k is None:
            return
        # Преобразование берём НА МОМЕНТ СНИМКА, а не последнее доступное.
        # Пока робот стоит, разницы нет, и все замеры сходились. Но стоит
        # поехать — и облако ляжет туда, где робот оказался к моменту
        # обработки, а не туда, откуда снимал. При 8 кадрах в секунду и
        # скорости 0.3 м/с это промах в несколько сантиметров каждый кадр,
        # и карта начнёт размазываться тем сильнее, чем быстрее едем.
        stamp = rclpy.time.Time.from_msg(m.header.stamp)
        try:
            tf = self.buf.lookup_transform(self.base, m.header.frame_id, stamp,
                                           timeout=rclpy.duration.Duration(
                                               seconds=0.1))
        except tf2_ros.TransformException as e:
            self.get_logger().warn(f'нет TF {self.base} <- {m.header.frame_id}: {e}',
                                   throttle_duration_sec=5.0)
            return

        step = int(self.get_parameter('step').value)
        rng = float(self.get_parameter('max_range').value)
        drop = float(self.get_parameter('drop_threshold').value)
        h = float(self.get_parameter('virtual_height').value)

        # Глубина приходит в двух видах, и это не мелочь. Gazebo отдаёт
        # 32FC1 в МЕТРАХ, а настоящий реалсенс — 16UC1 в МИЛЛИМЕТРАХ.
        # Разобрать второе как первое означает прочитать пары соседних
        # пикселей как одно число с плавающей точкой: получится мусор, но
        # мусор правдоподобного размера, и ошибка вылезет не сразу.
        if m.encoding == '16UC1':
            d = (np.frombuffer(m.data, np.uint16)
                 .reshape(m.height, m.width)[::step, ::step]
                 .astype(np.float32) * 0.001)
        else:
            d = np.frombuffer(m.data, np.float32).reshape(
                m.height, m.width)[::step, ::step]
        dopt = self.rays(m.height, m.width, step)
        ok = np.isfinite(d) & (d > 0.1) & (d < rng)
        if ok.sum() < 20:
            self.publish([], m.header.stamp)
            return

        q, t = tf.transform.rotation, tf.transform.translation
        R = self.quat_to_mat(q.x, q.y, q.z, q.w)
        O = np.array([t.x, t.y, t.z])
        # Оптический кадр даёт направление (xn, yn, 1), поэтому длина
        # вдоль луча совпадает со значением глубины — масштабировать не надо.
        dirs = dopt @ R.T
        P = (dopt * d[..., None]) @ R.T + O

        # Маску достаём ДО подгонки земли, а не только для раскраски.
        # Рельсы приподняты над настилом и, попав в окно подгонки, кренят
        # плоскость — замерено в симуляторе: 27.6% точек окна лежали на
        # трубах и давали 2.7 градуса на заведомо верных данных. Отбор по
        # самому населённому уровню эту беду сократил, но не убрал: остаток
        # около градуса, а это 3.5 см на двух метрах при пороге обрыва 6 см.
        # Если маска на этот кадр есть — исключаем трубы из оценки прямо.
        rail_sub = None
        _rf = self.mask_for(m.header.stamp)
        if _rf is not None and _rf[::step, ::step].shape == d.shape:
            rail_sub = _rf[::step, ::step]

        # Плоскость меряем, а не берём на веру (см. ground_fit выше).
        if bool(self.get_parameter('ground_fit').value):
            C, c = self.fit_ground(P, ok, rail_sub)
            if C is not None:
                # Поворот C кладёт измеренную землю горизонтально, сдвиг
                # опускает её на нуль. Весь дальнейший счёт — перелёт луча,
                # высоты, сетка — идёт уже относительно настоящей земли.
                #
                # ПОВОРОТ ИДЁТ ВОКРУГ КАМЕРЫ, А НЕ ВОКРУГ НАЧАЛА base_footprint.
                # Исправляем мы УГОЛ КРЕПЛЕНИЯ, а положение камеры измерено
                # рулеткой и сомнению не подлежит. Сначала здесь стояло
                # O = C @ O, то есть поворачивалась вся сцена вместе с
                # камерой вокруг точки между колёс. При |O| = 0.87 м и
                # поправке 2.7 градуса камера уезжала на 4.1 см — и ровно
                # такой сдвиг виден был в логе. Вертикальную часть съедала
                # поправка c, а горизонтальная оставалась, сдвигая всё
                # облако вперёд или назад.
                #
                # Высоту пересчитываем: после поворота вокруг камеры
                # плоскость оказывается на высоте c - (C O)z + Oz, её и
                # вычитаем, чтобы земля легла на нуль.
                R = C @ R
                # ИМЯ ЗДЕСЬ ВАЖНО. Сначала эта переменная называлась h — и
                # затирала virtual_height, взятую строками выше в ту же h.
                # Кромка после этого ложилась не на 30 см, а на величину
                # этого смещения, то есть на считанные сантиметры над
                # полом, и переставала быть препятствием для сетки. Снаружи
                # выглядело как «накопление границы сломалось», а параметр
                # virtual_height ни на что не влиял.
                plane_drop = c - float((C @ O)[2]) + float(O[2])
                O = np.array([O[0], O[1], O[2] - plane_drop])
                # Печатаем поправку: она и есть расхождение между двумя
                # отсчётами высоты в сцене. Рельсы и сетка занятости
                # строятся по ИСПРАВЛЕННОМУ облаку, а текстурная карта —
                # самим RTAB-Map из rgb+depth по URDF, без поправки. На
                # сколько они разойдутся, видно только отсюда.
                self.get_logger().info(
                    f'плоскость: наклон {math.degrees(math.acos(min(1.0, C[2, 2]))):.2f}°, '
                    f'сдвиг по высоте {plane_drop * 1000:+.0f} мм',
                    throttle_duration_sec=5.0)
                dirs = dopt @ R.T
                P = (dopt * d[..., None]) @ R.T + O

        # Кадр кладём в очередь ждать свою маску. Она придёт позже — на
        # замеренные 11-20 мс при полной частоте, дольше при пониженной, —
        # и тогда по этому же кадру поднимутся точки рельсов. Сам конвейер
        # глубины при этом ничего не ждёт: карта важнее рельсов.
        if bool(self.get_parameter('rail_accumulate').value):
            self.frames.append((
                int(m.header.stamp.sec) * 1_000_000_000
                + int(m.header.stamp.nanosec), m.header.stamp, d, R, O))
            del self.frames[:-int(self.get_parameter('rail_frames').value)]

        k_over = float(self.get_parameter('overshoot_k').value)
        floor_m = float(self.get_parameter('overshoot_min').value)
        over, s_plane = self.edge_by_ray(dirs, d, O, k_over, floor_m)
        over &= ok & (s_plane < float(self.get_parameter('edge_max_range').value))

        # ═══ Столбцы, где стоит предмет ═══
        # Рельс выше опорной плоскости, поэтому луч встречает его РАНЬШЕ
        # расчётного — это недолёт, знак обратный перелёту. Такие столбцы
        # выбрасываем целиком: кромку там всё равно загораживает труба, а
        # ложная стена поперёк рельсов помешает роботу отъехать назад
        # после неудачного заезда.
        margin = np.maximum(floor_m, k_over * s_plane ** 2)
        under = ok & (s_plane > 0.2) & (d < s_plane - margin) & \
            (s_plane < float(self.get_parameter('edge_max_range').value))
        blocked = under.sum(axis=0) >= int(self.get_parameter('block_rows').value)
        over[:, blocked] = False

        # Запоминаем, ГДЕ стоят препятствия: по одной точке на столбец,
        # ближайший недолёт. Зону без кромки зададим от них в МЕТРАХ.
        # Раньше я расширял её на соседние столбцы кадра, но ширина
        # столбца зависит от дальности — 5 мм на 1.1 м и 9.5 мм на 2 м, —
        # и одна и та же «четвёрка столбцов» давала разную зону.
        obst = np.zeros((0, 2))
        if blocked.any():
            cols_b = np.where(blocked)[0]
            rows_b = under.shape[0] - 1 - np.argmax(under[::-1][:, cols_b], axis=0)
            obst = P[rows_b, cols_b][:, :2]
        # В каждом столбце кадра берём ПЕРВЫЙ перелёт, считая от близкого
        # края. Нижняя строка кадра — ближняя земля, поэтому ищем самый
        # большой номер строки, где луч ещё перелетел. Без этого кромкой
        # окажется вся площадь за краем, а не её граница.
        # Перелёт должен держаться подряд: одиночный отсчёт — это шум или
        # узкая щель, а не край. Настоящий обрыв перелетают все лучи
        # дальше кромки, то есть подряд до самого верха кадра.
        run = int(self.get_parameter('min_run').value)
        # В кадре нижние строки — ближняя земля, верхние — дальняя.
        # Перелетают лучи, смотрящие ДАЛЬШЕ кромки, то есть строки ВЫШЕ.
        # Значит проверять надо строки с МЕНЬШИМ номером. Обратное условие
        # выполняется только вдали от края, и детектор убегает туда:
        # замерено — кромка определялась на 2.45 м вместо 1.1.
        sust = over.copy()
        for k in range(1, run):
            sust[k:] &= over[:-k]
        has = sust.any(axis=0)
        first = sust.shape[0] - 1 - np.argmax(sust[::-1], axis=0)
        # Медиана по последним кадрам: гасит дрожание от шума глубины.
        dist = np.where(has, s_plane[first, np.arange(len(has))], np.nan)
        n = int(self.get_parameter('smooth_frames').value)
        self._hist.append(dist)
        del self._hist[:-n]
        if len(self._hist) > 1 and all(h.shape == dist.shape for h in self._hist):
            with np.errstate(all='ignore'):
                dist = np.nanmedian(np.stack(self._hist), axis=0)
        # Медиана ПОПЕРЁК столбцов. В столбцах, где стоит рельс, луч
        # встречает трубу раньше плоскости, перелёта там нет, и первый
        # перелёт случается уже ЗА рельсом — точка кромки уезжает наружу.
        # На карте это выглядит как отростки кромки вдоль рельсов.
        # Таких столбцов мало, их значение — выброс, и медиана по соседям
        # возвращает его на линию края.
        w = int(self.get_parameter('cross_median').value)
        if w >= 3 and np.isfinite(dist).sum() > w:
            pad = np.pad(dist, w // 2, mode='edge')
            win = np.lib.stride_tricks.sliding_window_view(pad, w)
            with np.errstate(all='ignore'):
                dist = np.nanmedian(win, axis=1)

        # ЗАДЕЛКА КОРОТКИХ ПРОВАЛОВ по столбцам.
        #
        # Замерено: на метре от робота кромка закрыта на 100%, на двух — на
        # 42%. Шум растёт как квадрат дальности, и требование «перелёт
        # держится подряд» вдали срывается то в одном столбце, то в другом.
        # Граница получается пунктиром, а пунктир для Nav2 хуже, чем
        # отсутствие границы: в дырку between точками планировщик проложит
        # путь, и робот поедет за край.
        #
        # Кромка настила непрерывна, поэтому столбец без наблюдения между
        # двумя наблюдениями можно закрыть интерполяцией. Заделываем только
        # КОРОТКИЕ провалы и только внутри кадра: на краю кадра продолжать
        # линию не из чего, а длинный провал — это уже не шум, а рельс или
        # предмет, и придумывать там кромку нельзя.
        #
        # Честно говоря, на покрытие периметра это НЕ повлияло: 76/42/50%
        # до и 72/42/50% после. Провалы вдали оказались не одиночными
        # срывами, а систематическими. Держать робота на настиле должна не
        # сплошность линии, а то, что за кромкой клетки остаются
        # неизвестными. Заделка — дешёвая страховка от одиночных дырок, но
        # считать её решением нельзя.
        gap = int(self.get_parameter('edge_gap_fill').value)
        good = np.isfinite(dist)
        if gap > 0 and good.sum() >= 2:
            idx = np.arange(len(dist))
            filled = np.interp(idx, idx[good], dist[good])
            bad = (~good).astype(np.int8)
            edges_ = np.diff(np.r_[0, bad, 0])
            for a, b in zip(np.flatnonzero(edges_ == 1),
                            np.flatnonzero(edges_ == -1)):
                if a > 0 and b < len(dist) and b - a <= gap:
                    dist[a:b] = filled[a:b]

        has = np.isfinite(dist)
        cols = np.where(has)[0]
        rows = first[cols]
        # Точку кромки строим по СГЛАЖЕННОЙ дальности, а направление луча
        # берём из того же столбца — оно от шума не зависит.
        edge = (O + dist[cols, None] * dirs[rows, cols]) if len(cols) \
            else np.zeros((0, 3))
        # Рельсы из маски тоже задают зону без кромки, и делают это точнее
        # недолёта: недолёт ловит трубу только там, где луч в неё попал, а
        # маска знает всю трубу целиком. Из-за этой разницы одна точка
        # кромки садилась прямо между рельсами.
        rail = None
        if rail_sub is not None:
            rail = rail_sub & ok
            rp = P[rail][:, :2]
            if len(rp):
                obst = np.vstack([obst, rp[::max(1, len(rp) // 400)]])

        # Зона без кромки вокруг предметов, в метрах.
        r_block = float(self.get_parameter('block_radius').value)
        if len(edge) and len(obst):
            dmin = np.linalg.norm(edge[:, None, :2] - obst[None], axis=2).min(1)
            edge = edge[dmin > r_block]

        flat_ok = ok.reshape(-1)
        Pf = P.reshape(-1, 3)[flat_ok]
        railf = (rail.reshape(-1)[flat_ok] if rail is not None
                 else np.zeros(len(Pf), bool))
        low = Pf[:, 2] < drop
        self.report(Pf, low)

        # Облако для сетки: НИЖНИЙ УРОВЕНЬ В ОБЛАКО НЕ ИДЁТ ВОВСЕ.
        #
        # Раньше он подтягивался к опорной плоскости — пол ведь проезжий,
        # просто с другого уровня. Для стенда это неверно и опасно: площадь
        # за краем настила ложилась на карту СВОБОДНОЙ, и удерживала
        # планировщик одна тонкая линия края, а она местами рвётся.
        #
        # Поднимать нижний уровень на виртуальную высоту тоже не годится:
        # красным заливается всё поле зрения и карта перестаёт читаться.
        #
        # Решение проще обоих: не публиковать его совсем. Луч в ту сторону
        # не отправляется, трассировка там ничего не расчищает, и клетки
        # остаются НЕИЗВЕСТНЫМИ. Для Nav2 неизвестность непроезжая
        # (track_unknown_space у костмапа, allow_unknown: false у
        # планировщика), так что робот за край не поедет, а на карте
        # остаётся только линия кромки.
        G = Pf.copy()
        near = (np.linalg.norm(G[:, :2], axis=1)
                < float(self.get_parameter('grid_max_range').value)) & ~low

        # МЕДИАНА ПО КЛЕТКЕ вместо сырых точек.
        #
        # Шум дальномера растёт как квадрат дальности, и на двух метрах
        # его 95-й процентиль равен +30 мм — ровно порог, выше которого
        # RTAB-Map считает точку препятствием. Поэтому на ровной пустой
        # платформе каждая двадцатая точка перещёлкивалась в препятствие,
        # и по дальнему краю обзора высыпала зелёная сыпь.
        #
        # Шум независим по пикселям и симметричен, поэтому медиана по
        # клетке его срезает. Рельсы медианятся ОТДЕЛЬНО от пола: труба
        # тонкая, и в общей клетке точки пола её бы пересилили.
        cell = float(self.get_parameter('grid_cell').value)
        q_rail = self.cell_median(G[near & railf], cell)
        q_free = self.cell_median(G[near & ~railf], cell)

        # Вокруг рельса точки пола убираем. Сетка RTAB-Map усредняет цвет в
        # своём вокселе, и труба шириной 51 мм внутри клетки 50 мм всегда
        # оказывается в меньшинстве: замерено — в облаке детектора цвета
        # чистые, а после сетки вместо зелёного выходит (125,207,142), и
        # рельс на карте выглядит как обычное препятствие. Точки пола там
        # всё равно лишние: клетку занимает труба.
        clear = float(self.get_parameter('rail_clear_cell').value)
        if len(q_rail) and len(q_free):
            dmin = np.linalg.norm(q_free[:, None, :2] - q_rail[None, :, :2],
                                  axis=2).min(1)
            q_free = q_free[dmin > clear]

        # ПЯТАЧОК ПОД РОБОТОМ.
        #
        # Камера начинает видеть примерно с 0.6 м, поэтому площадь прямо под
        # роботом не наблюдается никогда и остаётся на карте неизвестной.
        # Для Nav2 неизвестность непроезжая, и робот оказывается в дыре:
        # замерено — клетка под ним имеет стоимость -1, вокруг 226
        # неизвестных клеток из 676, планировщик отказывается строить путь
        # от такого старта и цель падает с «Goal failed».
        #
        # Но эта площадь известна свободной по построению: робот на ней
        # стоит. Поэтому доклеиваем её сами.
        #
        # Пятачок намеренно МЕНЬШЕ корпуса. Корпус 1.22 x 0.90 м свисает за
        # колёса примерно на 0.28 м спереди и сзади, и у кромки настила этот
        # свес висит над обрывом. Объявить свободным то, подо что робот
        # свесился, — ровно та ошибка, из-за которой он и уезжал за край.
        # Колёсный прямоугольник 0.636 x 0.711 м опирается на опору всегда.
        fl = float(self.get_parameter('free_patch_length').value)
        fw = float(self.get_parameter('free_patch_width').value)
        if fl > 0 and fw > 0:
            gx, gy = np.meshgrid(np.arange(-fl / 2, fl / 2 + 1e-9, cell),
                                 np.arange(-fw / 2, fw / 2 + 1e-9, cell))
            patch = np.column_stack([gx.ravel(), gy.ravel(),
                                     np.zeros(gx.size)])
            q_free = np.vstack([q_free, patch]) if len(q_free) else patch

        # Цвет кладём в сами точки: RTAB-Map сливает кромку, рельсы и всё
        # прочее в одно облако препятствий, и покрасить их в RViz по
        # отдельности нельзя — цвет там задаётся на слой целиком.
        parts, cols = [], []
        for q, colour in ((q_free, (190, 190, 195)), (q_rail, (60, 225, 90))):
            if len(q):
                parts.append(q)
                cols.append(np.tile(np.array(colour, np.uint32), (len(q), 1)))
        if len(edge):
            parts.append(np.column_stack(
                [edge[:, 0], edge[:, 1], np.full(len(edge), h)]))
            cols.append(np.tile(np.array([235, 45, 45], np.uint32),
                                (len(edge), 1)))
        G = np.vstack(parts) if parts else np.zeros((0, 3))
        C = np.vstack(cols) if cols else np.zeros((0, 3), np.uint32)

        # ВОЗВРАЩАЕМ облако в кадр КАМЕРЫ, хотя считали всё в кадре робота.
        #
        # RTAB-Map берёт начало координат кадра облака за точку наблюдения и
        # прочерчивает лучи оттуда. Если отдать облако в base_footprint, он
        # считает, что сенсор стоит под роботом на уровне пола, и чистит
        # свободным всё вокруг этой точки — включая площадь ПОД роботом,
        # которую камера физически не видит. На карте это выглядит как
        # свободная область там, где наблюдений не было вовсе.
        #
        # Камера же стоит в 0.47 м впереди и на 0.74 м выше, и лучи из неё
        # идут совсем иначе. Поэтому пересчитываем обратно: G_cam = R^T (G - O).
        Gc = (G - O) @ R
        self.grid.publish(self.cloud(Gc.astype(np.float32), m.header.stamp,
                                     frame=m.header.frame_id, cols=C))

        out = np.column_stack([edge[:, 0], edge[:, 1],
                               np.full(len(edge), h)]).astype(np.float32) \
            if len(edge) else np.zeros((0, 3), np.float32)
        self.publish(out, m.header.stamp)



    def rays(self, h, w, step):
        """Единичные направления лучей в оптическом кадре, по пикселю.

        Зависят только от размера кадра, шага прореживания и калибровки,
        поэтому считаются однажды и кешируются. Раньше meshgrid со stack
        выполнялись на каждом кадре — это 1.2 МБ выделения тридцать раз в
        секунду впустую. Кеш нужен ещё и накопителю рельсов: он поднимает
        точки по кадру, снятому раньше, и обязан пользоваться той же
        сеткой, что и основной счёт.
        """
        key = (h, w, step, self.k)
        if getattr(self, '_rays_key', None) != key:
            fx, fy, cx, cy = self.k
            uu, vv = np.meshgrid((np.arange(0, w, step) - cx) / fx,
                                 (np.arange(0, h, step) - cy) / fy)
            self._rays_key = key
            self._rays = np.stack([uu, vv, np.ones_like(uu)], -1)
        return self._rays

    def accumulate_rails(self, mask, ns):
        """Помечает клетки карты, где увидены рельсы. Подробности замысла
        и его изъяна — в объявлении параметров rail_accumulate выше."""
        step = int(self.get_parameter('step').value)
        tol = float(self.get_parameter('rail_pair_tol').value)
        if not self.frames:
            return
        # Кадр глубины, снятый в тот же момент. Метки должны совпадать
        # точно: маска несёт header цветного кадра, а глубина выровнена по
        # цвету и несёт его же метку. Берём ближайшую с допуском на случай,
        # если выравнивание когда-нибудь отключат.
        fns, stamp, d, R, O = min(self.frames, key=lambda f: abs(f[0] - ns))
        if abs(fns - ns) * 1e-9 > tol:
            self.get_logger().warn(
                f'маске не нашлось кадра глубины ближе '
                f'{abs(fns - ns) * 1e-6:.0f} мс — в слой не кладу',
                throttle_duration_sec=5.0)
            return

        sub = mask[::step, ::step]
        if sub.shape != d.shape:
            return
        rng = float(self.get_parameter('rail_max_range').value)
        sel = sub & np.isfinite(d) & (d > 0.1) & (d < rng)
        n = int(sel.sum())
        if n < 10:
            return

        # Поднимаем ТОЛЬКО помеченные пиксели, а не весь кадр: их тысячи,
        # а не сотни тысяч, и вся операция укладывается в доли миллисекунды.
        dopt = self.rays(d.shape[0] * step, d.shape[1] * step, step)
        pts = dopt[sel] * d[sel][:, None]
        # R и O уже с поправкой на измеренную плоскость земли, поэтому
        # точки выходят в ИСПРАВЛЕННОМ кадре робота, а не в том, что
        # обещает URDF.
        pb = pts @ R.T + O

        # Отсекаем всё, что для рельса слишком высоко или низко (см.
        # rail_z_min выше). Делаем это В КАДРЕ РОБОТА, до перехода в
        # карту: высота относительно земли под роботом — величина
        # физическая, а в карте к ней примешался бы ещё и наклон пола.
        zb = pb[:, 2]
        keep = ((zb > float(self.get_parameter('rail_z_min').value))
                & (zb < float(self.get_parameter('rail_z_max').value)))
        if not keep.all():
            self.get_logger().info(
                f'вне полосы высот отброшено {int((~keep).sum())} точек '
                f'из {len(keep)}', throttle_duration_sec=10.0)
        pb = pb[keep]
        if len(pb) < 10:
            return

        cell = float(self.get_parameter('rail_voxel').value)

        # ПУТЬ С ПРИВЯЗКОЙ: кладём наблюдение в кадр УЗЛА графа, а не в
        # мировые клетки. Тогда слой поправится сам, когда граф уточнит
        # позу узла. Разбор — у параметра rail_graph_bind.
        if bool(self.get_parameter('rail_graph_bind').value):
            nid = self.node_for(ns * 1e-9)
            if nid is not None:
                pn = self.to_node_frame(pb, stamp, self.node_stamp[nid])
                if pn is not None:
                    local = self.obs.setdefault(nid, {})
                    idx = np.floor(pn / cell).astype(np.int32)
                    for key in map(tuple, idx):
                        local[key] = local.get(key, 0) + 1
                    if not self.bound:
                        self.get_logger().info(
                            'слой рельсов привязан к графу RTAB-Map')
                    self.bound = True
                    # graph_dirty здесь НЕ ставим. Новое наблюдение само
                    # по себе слой не меняет: он пересобирается по позам,
                    # а позы меняет только граф. Ближайшее сообщение
                    # mapGraph (2 Гц) всё равно придёт с этим узлом и
                    # вызовет пересборку, так что задержка не больше
                    # полусекунды, зато нет полной пересборки на каждую
                    # маску.
                    return

        # ЗАПАСНОЙ ПУТЬ: граф недоступен или узел не нашёлся — копим
        # как раньше, прямо в мировые клетки. Слой при этом не
        # поправляется, но лучше неисправляемый слой, чем никакого.
        if self.bound:
            self.get_logger().warn('граф потерян, вернулся к накоплению '
                                   'в odom без исправления',
                                   throttle_duration_sec=10.0)
        self.bound = False
        frame = str(self.get_parameter('rail_map_frame').value)
        try:
            tf = self.buf.lookup_transform(frame, self.base, stamp)
        except tf2_ros.TransformException:
            # Карты может ещё не быть: rtabmap публикует map->odom не сразу.
            # Это не ошибка, просто копить пока некуда.
            self.get_logger().warn(f'нет TF {frame} <- {self.base}, '
                                   f'рельсы пока не накапливаю',
                                   throttle_duration_sec=10.0)
            return
        q, t = tf.transform.rotation, tf.transform.translation
        pm = pb @ self.quat_to_mat(q.x, q.y, q.z, q.w).T + \
            np.array([t.x, t.y, t.z])

        idx = np.floor(pm / cell).astype(np.int32)
        v = self.rail_vox
        for key in map(tuple, idx):
            v[key] = v.get(key, 0) + 1

    def to_node_frame(self, pb, stamp, node_stamp_s):
        """Точки из кадра робота в кадр узла графа.

        Обе позы берём В ODOM и каждую на СВОЁ мгновение. Между
        наблюдением и узлом доли секунды, дрейф одометрии за это время
        пренебрежимо мал, а вот движение самого робота — нет: на 0.1 м/с
        четверть секунды это 25 мм, ровно воксель. Поэтому разность поз
        считается честно, а не отбрасывается как малая.
        """
        try:
            a = self.buf.lookup_transform('odom', self.base, stamp)
            b = self.buf.lookup_transform(
                'odom', self.base,
                rclpy.time.Time(nanoseconds=int(node_stamp_s * 1e9)))
        except tf2_ros.TransformException:
            return None
        qa, ta = a.transform.rotation, a.transform.translation
        qb, tb = b.transform.rotation, b.transform.translation
        Ra = self.quat_to_mat(qa.x, qa.y, qa.z, qa.w)
        Rb = self.quat_to_mat(qb.x, qb.y, qb.z, qb.w)
        Ta = np.array([ta.x, ta.y, ta.z])
        Tb = np.array([tb.x, tb.y, tb.z])
        # p_odom = Ra p + Ta;   p_node = Rb^T (p_odom - Tb)
        return (pb @ Ra.T + Ta - Tb) @ Rb

    # ── привязка слоя к графу RTAB-Map ────────────────────────────────
    def on_map_data(self, m):
        """Запоминаем, какому мгновению соответствует узел.

        Берём ТОЛЬКО id и метку: поле data у узла несёт снимки и облака,
        и трогать его незачем. Метки нужны затем, чтобы сопоставить наше
        наблюдение с узлом — в mapGraph их нет.
        """
        for n in m.nodes:
            self.node_stamp[int(n.id)] = float(n.stamp)

    def on_graph(self, m):
        """Новые позы узлов. Если хоть одна сдвинулась — слой пересобрать."""
        moved = False
        seen = set()
        for i, pose in zip(m.poses_id, m.poses):
            i = int(i)
            seen.add(i)
            q, t = pose.orientation, pose.position
            R = self.quat_to_mat(q.x, q.y, q.z, q.w)
            T = np.array([t.x, t.y, t.z])
            old = self.node_pose.get(i)
            # Порог вчетверо мельче вокселя: сдвиг меньше него слой всё
            # равно не изменит, а пересборка стоит времени.
            if old is None or np.abs(old[1] - T).max() > 0.006 \
                    or np.abs(old[0] - R).max() > 0.004:
                moved = True
            self.node_pose[i] = (R, T)
        # Узлы, пропавшие из графа (сброс одометрии, уход в долговременную
        # память), удаляем ИЗ ПОЗ, но НЕ из наблюдений: вернётся узел —
        # вернутся и его точки, уже на правильном месте.
        gone = set(self.node_pose) - seen
        if gone:
            for i in gone:
                del self.node_pose[i]
            moved = True
        if moved:
            self.graph_dirty = True

    def node_for(self, stamp_s):
        """Узел, ближайший по времени к наблюдению, или None."""
        if not self.node_stamp:
            return None
        i = min(self.node_stamp, key=lambda k: abs(self.node_stamp[k] - stamp_s))
        if abs(self.node_stamp[i] - stamp_s) > \
                float(self.get_parameter('rail_node_tol').value):
            return None
        return i

    def rebuild_rails(self):
        """Собрать слой заново из наблюдений по текущим позам узлов.

        Это и есть всё лечение: наблюдения не трогаются, меняются только
        позы, по которым их раскладывают. Ровно так поступает и сам
        RTAB-Map со своей сеткой.
        """
        # ЦЕНА. Пересборка идёт по всем узлам и всем их клеткам разом, и
        # растёт линейно с размером сцены. На стенде это десятки узлов по
        # сотне-другой клеток, доли миллисекунды. Если сцена станет
        # большой и это начнёт быть заметно в профиле — пересобирать
        # только узлы, чьи позы изменились, а остальные держать готовыми.
        # Пока не усложняем: замеров, что это дорого, нет.
        cell = float(self.get_parameter('rail_voxel').value)
        v = {}
        for i, local in self.obs.items():
            pose = self.node_pose.get(i)
            if pose is None:
                continue                # узел сейчас не размещается
            R, T = pose
            keys = np.array(list(local.keys()), np.float64)
            if not len(keys):
                continue
            cnt = np.fromiter(local.values(), np.int32, len(local))
            pm = (keys + 0.5) * cell @ R.T + T
            idx = np.floor(pm / cell).astype(np.int32)
            for key, c in zip(map(tuple, idx), cnt):
                v[key] = v.get(key, 0) + int(c)
        self.rail_vox = v
        self.graph_dirty = False

    def fit_rails(self, V):
        """ПОЗА двух труб известной геометрии по накопленным клеткам.

        ЧТО ЗДЕСЬ БЫЛО РАНЬШЕ И ПОЧЕМУ ЭТО НЕ РАБОТАЛО. Стояло деление
        точек пополам ПО МЕДИАНЕ поперёк и два центра тяжести. Подгонки
        фигуры к облаку не было вовсе: цилиндры потом просто рисовались по
        полученной оси и с данными ни разу не сверялись.

        Губил такую оценку загиб П. Он пересекает колею поперёк на всю
        ширину и лежит на той же высоте, что трубы, — отличить его по
        высоте нельзя. А деление по медиане обязано раздать его точки в
        обе половины, и обе тянутся к середине. Замерено на стенде по
        1546 клеткам: колея выходила 496 мм с загибом против 537 мм без
        него при истинных 526. Сорок миллиметров ошибки, и туда же
        уезжали ось с направлением.

        ЧТО ЗДЕСЬ ТЕПЕРЬ. Размеры трубы и колея ИЗВЕСТНЫ и фиксированы,
        поэтому искать нужно не форму, а ПОЛОЖЕНИЕ известной фигуры. Две
        параллельные прямые на земле имеют всего две степени свободы:
        поворот th и поперечный сдвиг s. Это задача о позе, а не о
        подгонке кривой, и решается она устойчиво.

        Этап 1. Грубый перебор по сетке (th, s) — обобщённое
        преобразование Хафа. Для каждого угла точки проецируются поперёк,
        строится гистограмма, и она сворачивается с двугорбым шаблоном
        «две полосы на расстоянии колеи». Выигрывает положение, собравшее
        больше всего клеток. Лишние точки — загиб, мусор, отражения — при
        таком подсчёте просто не голосуют ни за что и решение НЕ ТЯНУТ, в
        отличие от среднего. Начального приближения не нужно, локальных
        минимумов нет по построению.

        Этап 2. Уточнение методом Гаусса-Ньютона по невязке «расстояние
        от клетки до ближайшей оси трубы», с перевзвешиванием (IRLS) и
        ядром Коши. Ядро и есть защита от шума: клетка, лежащая вдвое
        дальше масштаба ядра, получает вчетверо меньший вес, а не
        квадратично больший, как в чистом МНК. Масштаб взят равным
        радиусу трубы.

        Этап 3. Начало рельсов. Когда оси найдены, это задача с ОДНИМ
        неизвестным. Клетки, попавшие МЕЖДУ трубами, принадлежат загибу:
        замерено, что все 154 такие клетки лежали в крайней четверти
        длины, а на остальных 1.1 м не было ни одной. Их крайняя точка
        вдоль оси и есть торец.

        ВЫСОТА. Труба лежит НА настиле, значит ось её центра на радиус
        выше него. Низ накопленного столба клеток и есть уровень настила,
        отсюда высота оси. Брать медиану столба нельзя: видно
        преимущественно ВЕРХ трубы, и медиана завышена.

        Честная оговорка: ты предлагал опираться на плоскость настила по
        полосам 5 см сбоку от труб. В накопителе её нет — он хранит
        только клетки, помеченные рельсом, а точки настила выбрасываются
        ещё в accumulate_rails. Поэтому уровень берётся по низу самих
        труб. Разница в том, что настоящая плоскость дала бы ещё и наклон,
        а так получается одна высота на всю фигуру. Для нынешних данных
        это неважно: уклон слоя вдоль рельсов замерен в 0.25 градуса, то
        есть 6.7 мм на полтора метра — вчетверо меньше клетки в 25 мм.
        """
        if len(V) < 20:
            return None
        P = np.asarray(V[:, :2], np.float64)
        g = float(self.get_parameter('rail_gauge').value)
        rad = 0.5 * float(self.get_parameter('rail_pipe_d').value)
        half = 0.5 * g
        tol = rad + float(self.get_parameter('rail_fit_tol').value)
        c = P.mean(0)
        X = P - c

        # ═══ Этап 1: перебор по сетке (угол, поперечный сдвиг) ═══
        binw = 0.005
        rmax = float(np.abs(X).max()) + half + tol + binw
        edges = np.arange(-rmax, rmax + binw, binw)
        ctr = edges[:-1] + 0.5 * binw
        kd = np.arange(-(half + tol), half + tol + binw, binw)
        # Шаблон: две полосы шириной 2*tol на расстоянии колеи друг от
        # друга. Симметричен, поэтому свёртка равна корреляции.
        kern = (np.abs(np.abs(kd) - half) < tol).astype(np.float64)
        step = math.radians(float(
            self.get_parameter('rail_fit_angle_step').value))
        best = (-1.0, 0.0, 0.0)
        for th in np.arange(0.0, math.pi, step):
            n = np.array([-math.sin(th), math.cos(th)])
            h, _ = np.histogram(X @ n, bins=edges)
            sc = np.convolve(h.astype(np.float64), kern, mode='same')
            i = int(np.argmax(sc))
            if sc[i] > best[0]:
                best = (float(sc[i]), float(th), float(ctr[i]))
        _, th, sft = best

        # ═══ Этап 2: уточнение (IRLS, ядро Коши) ═══
        # Невязка r = q - s - sgn*half, где sgn говорит, к какой из двух
        # труб клетка ближе. Производные: dr/dth = -t, dr/ds = -1.
        ck = max(rad, 1e-3)
        for _ in range(int(self.get_parameter('rail_fit_iters').value)):
            u = np.array([math.cos(th), math.sin(th)])
            n = np.array([-math.sin(th), math.cos(th)])
            q, t = X @ n, X @ u
            sgn = np.where(q >= sft, 1.0, -1.0)
            r = q - sft - sgn * half
            w = 1.0 / (1.0 + (r / ck) ** 2)
            J = np.stack([-t, -np.ones_like(t)], 1)
            Jw = J * w[:, None]
            try:
                d = np.linalg.solve(Jw.T @ J, -(Jw.T @ r))
            except np.linalg.LinAlgError:
                break
            th += float(d[0])
            sft += float(d[1])
            if abs(d[0]) < 1e-6 and abs(d[1]) < 1e-6:
                break

        u = np.array([math.cos(th), math.sin(th)])
        n = np.array([-math.sin(th), math.cos(th)])
        q, t = X @ n, X @ u
        dev = np.abs(np.abs(q - sft) - half)
        on = dev < tol
        if int(on.sum()) < 20:
            return None
        # Клетки МЕЖДУ трубами: ближе к середине, чем ПОЛОСА ДОПУСКА
        # вокруг труб. Порог именно half - tol, а не half - rad.
        #
        # Сначала стояло half - rad, и полосы перекрывались: труба
        # засчитывалась с допуском tol (48 мм), то есть до 215 мм от
        # середины, а «между трубами» начиналось с 235. Клетки из полосы
        # 215...235 попадали в оба множества сразу. Замерено на стенде:
        # 1168 на трубах плюс 475 на загибе при 1442 клетках всего.
        # Загиб оказывался забит рельсовыми клетками со ВСЕЙ длины, его
        # медиана вдоль оси совпадала с медианой труб — и выбор стороны
        # загиба ниже превращался в подбрасывание монеты.
        mid = np.abs(q - sft) < (half - tol)

        # ═══ Этап 3: с какого конца загиб ═══
        # Рисование ждёт загиб на МАЛЫХ t. Если он оказался с другой
        # стороны, разворачиваем систему на pi: тогда u, n, q, t и s
        # меняют знак разом и остальной код трогать не нужно.
        if int(mid.sum()) >= 5 and np.median(t[mid]) > np.median(t[on]):
            th += math.pi
            u, n = -u, -n
            q, t, sft = -q, -t, -sft
        # ═══ ПЕРЕМЫЧКА ВПИСЫВАЕТСЯ КАК ОТДЕЛЬНЫЙ ЦИЛИНДР ═══
        #
        # Она перпендикулярна трубам, значит её поза — ОДНА неизвестная,
        # положение вдоль оси. Ищем тем же приёмом, что и трубы:
        # гистограмма клеток «между трубами» вдоль оси, свёртка с окном
        # шириной в диаметр трубы с допуском, пик и есть перемычка.
        #
        # ЧЕГО ЭТИМ ИЗБЕГАЕМ. Раньше торец выводился из ПРЕДПОЛАГАЕМОГО
        # радиуса загиба: t0 = кончик + R, где R брался параметром. Но R
        # не измерен, и проверка показала, что ошибка торца в точности
        # равна ошибке R — то есть фигура садилась ровно настолько, на
        # сколько мы угадали радиус. Теперь наоборот: вписываем перемычку,
        # а радиус СЧИТАЕМ из её длины, R = (колея - длина) / 2.
        #
        # До этого торец брался как t[on].min(), край клеток на трубах, и
        # промахивался ещё грубее. Дуга возле точки касания идёт почти
        # вдоль прямой: отклонение растёт как s^2/(2R), и при радиусе
        # около 263 мм она не выходит за допуск 48 мм на протяжении
        # sqrt(2*0.263*0.048) = 159 мм. Столько дуги засчитывалось в
        # прямую, и ещё столько же откладывало рисование.
        R_fit = float(self.get_parameter('rail_bend_r').value)
        t0 = float(t[on].min())
        if int(mid.sum()) >= 10:
            tb = t[mid]
            hw = rad + float(self.get_parameter('rail_fit_tol').value)
            bw = 0.005
            e2 = np.arange(tb.min() - hw, tb.max() + hw + bw, bw)
            if len(e2) > 3:
                h2, _ = np.histogram(tb, bins=e2)
                win = np.ones(max(1, int(round(2 * hw / bw))))
                sc2 = np.convolve(h2.astype(np.float64), win, mode='same')
                t_cb = float(e2[int(np.argmax(sc2))] + 0.5 * bw)
                # РАДИУС ЗАГИБА ОСТАЁТСЯ ПАРАМЕТРОМ, и это проверено.
                #
                # Пробовали достать его из данных двумя способами, оба
                # негодны при нынешнем разбросе клеток поперёк (35 мм при
                # трубе 56). Через длину перемычки, R = (колея - длина)/2:
                # возле перемычки дуга идёт ПОПЕРЁК и за окно допуска
                # успевает распахнуться почти на всю колею, так что в
                # «длину» попадают дуги — на искусственной П с известным
                # ответом выходило 23, 48, 43, 54 мм вместо 80, 110, 145,
                # 200. Через точку входа дуги в полосу труб,
                # R = (tol + D) + sqrt(2*tol*D): арифметика точна (80 ->
                # 80.0), но D завышается разбросом втрое, и выходило 136,
                # 168, 152, 182 мм вместо тех же 80...200.
                #
                # Что РАБОТАЕТ — положение самой перемычки: на той же
                # проверке она садилась в -1...+14 мм от кончика фигуры.
                # Поэтому торец строим от неё, а радиус берём заданный.
                t0 = t_cb + R_fit
        t1 = float(t[on].max())

        A, B = q[on & (q > sft)], q[on & (q <= sft)]
        gauge_meas = (float(abs(A.mean() - B.mean()))
                      if len(A) and len(B) else float('nan'))

        # ═══ Высота: низ столба клеток плюс радиус ═══
        cell = float(self.get_parameter('rail_voxel').value)
        zi = np.asarray(V[on, 2], np.float64)
        deck = float(np.quantile(zi, 0.05)) - 0.5 * cell
        z = deck + rad

        axis = c + n * sft
        return (axis, u, n, gauge_meas, t0, t1, z,
                int(on.sum()), int(mid.sum()), R_fit)

    def tube(self, mid, p0, p1, z, d, rgb=(0.2, 0.9, 0.3)):
        """Отрезок трубы цилиндром. Задаём двумя концами: так не ошибиться
        с кватернионом, он выводится из направления."""
        m = Marker()
        m.header.frame_id = self.layer_frame()
        m.header.stamp = self.get_clock().now().to_msg()
        m.ns, m.id = 'rail_model', mid
        m.type, m.action = Marker.CYLINDER, Marker.ADD
        v = np.array([p1[0] - p0[0], p1[1] - p0[1], 0.0])
        L = float(np.linalg.norm(v))
        if L < 1e-4:
            return None
        v /= L
        # Цилиндр смотрит вдоль своей оси Z. Поворот, совмещающий Z с v:
        # ось вращения Z x v, угол 90 градусов, раз v горизонтален.
        m.pose.position.x = float((p0[0] + p1[0]) / 2)
        m.pose.position.y = float((p0[1] + p1[1]) / 2)
        m.pose.position.z = float(z)
        k = math.sqrt(0.5)
        m.pose.orientation.x, m.pose.orientation.y = -v[1] * k, v[0] * k
        m.pose.orientation.z, m.pose.orientation.w = 0.0, k
        m.scale.x = m.scale.y = float(d)
        m.scale.z = L
        m.color.r, m.color.g, m.color.b, m.color.a = (*rgb, 0.75)
        return m

    def publish_rail_model(self, fit):
        """Фигура с ИЗВЕСТНЫМИ размерами на найденной оси. Совпадёт с
        клетками — значит нашли верно; разойдётся — видно сразу."""
        a = MarkerArray()
        axis, u, n, gauge_meas, t0, t1, z, n_on, n_mid, R = fit
        wipe = Marker()
        wipe.header.frame_id = self.layer_frame()
        wipe.header.stamp = self.get_clock().now().to_msg()
        wipe.ns, wipe.action = 'rail_model', Marker.DELETEALL
        a.markers.append(wipe)
        g = float(self.get_parameter('rail_gauge').value)
        d = float(self.get_parameter('rail_pipe_d').value)
        half = g / 2.0

        def pt(t, sv):
            return axis + u * t + n * sv

        mid = 0
        for sgn in (+1, -1):
            # Прямая нитка на всю наблюдаемую длину.
            m = self.tube(mid, pt(t0, sgn * half), pt(t1, sgn * half), z, d)
            mid += 1
            if m:
                a.markers.append(m)
            if R <= 0.0:
                continue
            # Угол П: четверть окружности радиусом R, от начала нитки
            # внутрь. Центр смещён поперёк на R от самой нитки.
            c_t, c_s = t0, sgn * (half - R)
            prev = pt(t0, sgn * half)
            for i in range(1, 9):
                phi = (math.pi / 2) * i / 8
                p = pt(c_t - R * math.sin(phi), c_s + sgn * R * math.cos(phi))
                m = self.tube(mid, prev, p, z, d)
                mid += 1
                if m:
                    a.markers.append(m)
                prev = p
        # Перемычка П: прямая между концами углов, длина g - 2R.
        if R > 0.0:
            m = self.tube(mid, pt(t0 - R, half - R),
                          pt(t0 - R, -(half - R)), z, d)
            mid += 1
            if m:
                a.markers.append(m)

        # ПОДПИСЬ УБРАНА ИЗ СЦЕНЫ. Текстовый маркер висел в воздухе
        # растянутой строкой и читался кусками, мешая смотреть на карту.
        # Те же числа уходят в лог раз в пять секунд — там их и смотреть.
        self.get_logger().info(
            f'рельсы: колея {gauge_meas * 1000:.0f} мм (истинная '
            f'{g * 1000:.0f}), длина {t1 - t0:.2f} м, радиус загиба '
            f'{R * 1000:.0f} мм, клеток на трубах {n_on}, на загибе {n_mid}',
            throttle_duration_sec=5.0)
        self.model_pub.publish(a)

    def layer_frame(self):
        """Кадр, в котором сейчас живёт слой рельсов.

        При привязке к графу позы узлов приходят в `map`, значит и слой
        выходит в `map`. Без привязки — прежний `rail_map_frame` (odom).
        Потребители кадр не предполагают, а читают из заголовка: заезд
        делает это в on_cloud и on_rail_pose, поэтому переключение им
        прозрачно.
        """
        if self.bound:
            return 'map'
        return str(self.get_parameter('rail_map_frame').value)

    def publish_rails(self):
        # Пересобираем слой, только если граф что-то подвинул. Пересборка
        # идёт по всем узлам сразу, поэтому делать её на каждый кадр
        # незачем — позы меняются редко, на замыканиях петли.
        if self.graph_dirty:
            self.rebuild_rails()
        if not self.rail_vox:
            return
        need = int(self.get_parameter('rail_min_hits').value)
        keys = sorted(k for k, c in self.rail_vox.items() if c >= need)
        if not keys:
            return
        cell = float(self.get_parameter('rail_voxel').value)
        # Центры клеток, а не углы: иначе кубики в RViz встанут со сдвигом
        # в полклетки относительно карты.
        v = (np.asarray(keys, np.float32) + 0.5) * cell
        cols = np.tile(np.array([[60, 225, 90]], np.uint8), (len(v), 1))
        hdr_stamp = self.get_clock().now().to_msg()
        self.rail_pub.publish(self.cloud(
            v, hdr_stamp, frame=self.layer_frame(), cols=cols))
        # Подгонка идёт по ТЕМ ЖЕ подтверждённым клеткам, что ушли в
        # слой, и считается ОДИН раз и кормит обоих потребителей: позу
        # для заезда и фигуру для глаз. Раньше её звала только отрисовка
        # модели, и заезд искал ось заново своей копией алгоритма — с
        # делением по медиане, то есть тем самым, что промахивалось на
        # сорок миллиметров из-за загиба.
        fit = self.fit_rails(v)
        if fit is not None:
            self.publish_rail_pose(fit)
            if bool(self.get_parameter('rail_model').value):
                self.publish_rail_model(fit)

    def publish_rail_pose(self, fit):
        """Начало рельсов и их направление — то, что нужно заезду.

        Положение это ТОРЕЦ (начало прямых участков), а не середина:
        автомат отсчитывает от него и точку старта, и пройденный путь.
        Поворот — курс вдоль рельсов, от торца вдаль.
        """
        axis, u, _n, _g, t0, _t1, z = fit[:7]
        p = axis + u * t0
        m = PoseStamped()
        m.header.frame_id = self.layer_frame()
        m.header.stamp = self.get_clock().now().to_msg()
        m.pose.position.x = float(p[0])
        m.pose.position.y = float(p[1])
        m.pose.position.z = float(z)
        yaw = math.atan2(float(u[1]), float(u[0]))
        m.pose.orientation.z = math.sin(0.5 * yaw)
        m.pose.orientation.w = math.cos(0.5 * yaw)
        self.rail_pose_pub.publish(m)

    def fit_ground(self, P, ok, exclude=None):
        """Опорная плоскость по ближней земле под роботом.

        Возвращает поворот C, кладущий найденную землю горизонтально, и
        высоту c, на которую её после этого надо опустить до нуля. Если
        земли в кадре не видно или поправка вышла неправдоподобной,
        возвращает (None, 0) — тогда остаёмся на плоскости из URDF.
        """
        rng = float(self.get_parameter('ground_fit_range').value)
        band = float(self.get_parameter('ground_fit_band').value)
        r = np.hypot(P[..., 0], P[..., 1])
        sel = ok & (r < rng) & (np.abs(P[..., 2]) < band)
        # Всё, что помечено рельсом, землёй быть не может по определению.
        if exclude is not None and exclude.shape == sel.shape:
            sel = sel & ~exclude
        if sel.sum() < 500:
            return None, 0.0
        G = P[sel]

        # ЗАТРАВКА ПО САМОМУ НАСЕЛЁННОМУ УРОВНЮ, а не по медиане.
        #
        # Сначала здесь стояла медиана с полосой +-5 см. На стенде с
        # рельсами это оказалось неверно: замерено в симуляторе, где URDF
        # точен по построению, в окне подгонки 12133 точки, из них 3347
        # (27.6%) лежат на рельсах высотой +4.3 см. В полосу +-5 см вокруг
        # медианы они попадают целиком, расположены несимметрично — и
        # кренят плоскость на 2.7 градуса, поднимая её на 4.6 см. То есть
        # подгонка ПОРТИЛА заведомо правильную плоскость.
        #
        # Самый населённый уровень от этого защищён: настил под роботом
        # даёт на порядок больше точек, чем тонкая труба. Гистограмма по
        # 2 см, берём центр самой полной корзины.
        #
        # Полоса вокруг затравки НЕСИММЕТРИЧНА: вниз 3 см, вверх 2 см.
        # Земля — это нижняя поверхность, всё приподнятое над ней (рельсы,
        # предметы, мусор) в оценку попадать не должно. Симметричная полоса
        # этого не обеспечивает, а узкая симметричная срезала бы и сам
        # наклон, который мы ищем.
        lo, hi = float(G[:, 2].min()), float(G[:, 2].max())
        nb = max(2, int(round((hi - lo) / 0.02)))
        cnt, edges = np.histogram(G[:, 2], bins=nb, range=(lo, hi))
        k = int(np.argmax(cnt))
        z0 = 0.5 * (edges[k] + edges[k + 1])
        G = G[(G[:, 2] > z0 - 0.03) & (G[:, 2] < z0 + 0.02)]
        if len(G) < 300:
            return None, 0.0

        A = np.c_[G[:, 0], G[:, 1], np.ones(len(G))]
        coef = None
        for _ in range(2):
            coef = np.linalg.lstsq(A, G[:, 2], rcond=None)[0]
            keep = np.abs(G[:, 2] - A @ coef) < 0.03
            if keep.sum() < 300:
                break
            G, A = G[keep], A[keep]
        a, b, c0 = (float(v) for v in coef)

        # z = a x + b y + c  ->  нормаль (-a, -b, 1).
        nv = np.array([-a, -b, 1.0])
        nn = float(np.linalg.norm(nv))
        nv /= nn
        c = c0 / nn
        tilt = math.degrees(math.acos(min(1.0, max(-1.0, float(nv[2])))))
        if tilt > float(self.get_parameter('ground_fit_max_tilt').value) or \
                abs(c) > float(self.get_parameter('ground_fit_max_shift').value):
            self.get_logger().warn(
                f'подгонка земли отвергнута: наклон {tilt:.1f} град, '
                f'сдвиг {c * 100:+.0f} см — остаюсь на URDF',
                throttle_duration_sec=5.0)
            return None, 0.0

        # Копим измерения и применяем МЕДИАНУ, а не последнее. Медиана
        # покомпонентно с последующей нормировкой: углы тут малые, и
        # честное усреднение на сфере ничего бы не добавило.
        self._gfit.append((nv[0], nv[1], nv[2], c))
        del self._gfit[:-int(self.get_parameter('ground_fit_samples').value)]
        med = np.median(np.asarray(self._gfit, np.float64), axis=0)
        nv = med[:3] / np.linalg.norm(med[:3])
        c = float(med[3])
        tilt = math.degrees(math.acos(min(1.0, max(-1.0, float(nv[2])))))

        # Поворот, совмещающий нормаль с вертикалью (формула Родрига).
        v = np.cross(nv, (0.0, 0.0, 1.0))
        sn = float(np.linalg.norm(v))
        if sn < 1e-9:
            C = np.eye(3)
        else:
            K = np.array([[0.0, -v[2], v[1]],
                          [v[2], 0.0, -v[0]],
                          [-v[1], v[0], 0.0]])
            C = np.eye(3) + K + K @ K * ((1.0 - float(nv[2])) / sn ** 2)
        self._ground = (tilt, c)
        return C, c

    def edge_by_ray(self, dirs, depth, O, k=0.010, floor_m=0.03):
        """Кромка там, где луч перестал попадать в опорную плоскость.

        Для каждого пикселя считаем, на каком расстоянии луч встретил бы
        плоскость z=0 (та, на которой стоит робот). Если измеренная
        глубина заметно больше — луч перелетел край и упал на нижний
        уровень. Граница между «попал» и «перелетел» и есть кромка.

        Признак геометрический, а не статистический, и поэтому не зависит
        ни от плотности точек, ни от того, что попало в клетку. До этого
        я трижды пробовал эвристики на сетке — раздувание опоры, точки
        уровня пола, перепад минимальной высоты, — и каждая спотыкалась
        по-своему: бок рельса даёт точки на всех высотах сразу, а на
        дистанции в клетке может вообще не оказаться отсчётов, и пустая
        клетка выглядит опорой.

        Рельсы этому признаку не мешают: препятствие встречается РАНЬШЕ
        ожидаемого, а не позже, и на кромку не похоже.

        Возвращает маску тех точек, что стоят последними перед перелётом.
        """
        # Работаем с любой формой: сюда приходит сетка кадра (H, W, 3).
        dz = dirs[..., 2]
        # Луч должен идти вниз, иначе плоскости он не встретит вовсе.
        down = dz < -1e-3
        s_plane = np.full(dz.shape, np.inf, np.float32)
        s_plane[down] = -O[2] / dz[down]
        margin = np.maximum(floor_m, k * s_plane ** 2)
        over = down & (depth > s_plane + margin) & (s_plane > 0.2)
        return over, s_plane

    def report(self, P, low):
        """Раз в пять секунд говорим, что вообще видим. Без этого молчащий
        детектор неотличим от сломанного."""
        g = getattr(self, '_ground', None)
        fit = (f', земля подогнана: наклон {g[0]:.1f} град, сдвиг {g[1] * 100:+.0f} см'
               if g else ', земля по URDF')
        need = int(self.get_parameter('rail_min_hits').value)
        conf = sum(1 for c in self.rail_vox.values() if c >= need)
        rails = (f', рельсов {conf} клеток подтверждено из '
                 f'{len(self.rail_vox)}' if self.rail_vox else '')
        self.get_logger().info(
            f'точек {len(P)}, высота {P[:, 2].min():+.2f}..{P[:, 2].max():+.2f} м, '
            f'ниже порога {int(low.sum())}{fit}{rails}',
            throttle_duration_sec=5.0)

    @staticmethod
    def cell_median(G, cell):
        """По одной точке на клетку — той, что с медианной высотой."""
        if not len(G) or cell <= 0:
            return G
        key = np.floor(G[:, :2] / cell).astype(np.int64)
        kk = key[:, 0] * 1000003 + key[:, 1]
        order = np.lexsort((G[:, 2], kk))
        Gs, ks = G[order], kk[order]
        beg = np.flatnonzero(np.r_[True, ks[1:] != ks[:-1]])
        end = np.r_[beg[1:], len(ks)]
        return Gs[(beg + end) // 2]

    def cloud(self, pts, stamp, frame=None, cols=None):
        hdr = Header(stamp=stamp, frame_id=frame or self.base)
        fields = [PointField(name=n, offset=i * 4, datatype=PointField.FLOAT32,
                             count=1) for i, n in enumerate(('x', 'y', 'z'))]
        if cols is None:
            return pc2.create_cloud(
                hdr, fields, pts if len(pts) else np.zeros((0, 3), np.float32))
        fields.append(PointField(name='rgb', offset=12,
                                 datatype=PointField.FLOAT32, count=1))
        if not len(pts):
            return pc2.create_cloud(hdr, fields, np.zeros((0, 4), np.float32))
        c = cols.astype(np.uint32)
        packed = (c[:, 0] << 16) | (c[:, 1] << 8) | c[:, 2]
        rgb = np.ascontiguousarray(packed, np.uint32).view(np.float32)
        return pc2.create_cloud(
            hdr, fields,
            np.column_stack([pts.astype(np.float32), rgb]).astype(np.float32))

    def publish(self, pts, stamp):
        self.pub.publish(self.cloud(pts, stamp))

    @staticmethod
    def quat_to_mat(x, y, z, w):
        return np.array([
            [1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
            [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
            [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]])


