"""Прошивка MicroPython для Pico: MPU6050 -> поток кадров по USB.

Переделана из прошивки дипломного стенда `inputshaping_robot`
(`pico_firmware/main.py`). Распайка и приёмы работы с I2C взяты оттуда без
изменений, потому что они проверены на живом железе:

    Pico GP0 (ножка 1)  -> MPU6050 SDA
    Pico GP1 (ножка 2)  -> MPU6050 SCL
    Pico 3V3 (ножка 36) -> MPU6050 VCC
    Pico GND (ножка 38) -> MPU6050 GND и AD0 (AD0 на землю = адрес 0x68)

ЧТО ИЗМЕНЕНО ПО СУЩЕСТВУ

Там снимался ТОЛЬКО акселерометр: задача была мерить вибрацию, и угловая
скорость для неё не нужна. Здесь датчик работает как ИНС для одометрии, а
ей нужны обе величины сразу — иначе нечем ни удержать ориентацию между
кадрами камеры, ни отличить поворот от смещения. Поэтому в FIFO включены и
акселерометр, и гироскоп, кадр вырос с 14 до 20 байт.

FIFO НЕ ИСПОЛЬЗУЕТСЯ, в отличие от прошивки стенда. Там он был нужен,
чтобы не терять выборки на килогерце при заминке USB. Но у FIFO нет меток
границ пакета: если чтение однажды начнётся не с начала выборки, поток
поедет со смещением НАВСЕГДА, и снаружи это выглядит как перепутанные оси.
Замерено на живой плате: лежащий плашмя датчик отдавал тяжесть по x,
тогда как прямое чтение регистров честно показывало её по z, расхождение
10.3 м/с². В прошивке стенда тот же изъян давал тяжесть по y, и там его
не заметили — для спектра вибраций номер оси не важен.

Попытка выровнять FIFO сбросом и проверкой при запуске проблему не сняла:
проверка проходила, а на ходу выравнивание всё равно терялось. Поэтому
FIFO убран целиком. Чтение двенадцати регистров напрямую занимает около
1.4 мс на шине 100 кГц, то есть 28% времени при 200 Гц — с запасом. Заодно
метка времени становится точной, а не восстановленной по номеру выборки.

Частота снижена с 1 кГц до 200 Гц. Тысяча выборок в секунду нужна была,
чтобы ловить резонансы конструкции; одометрии столько не нужно, а лишний
поток по USB только увеличивает задержку и риск переполнения FIFO при
заминке хоста.

Диапазоны подняты до +-4 g и +-500 град/с. На стенде хватало +-2 g, но
здесь робот заезжает на рельсы со ступенькой и ударом, и упереться в
предел шкалы в этот самый момент — значит потерять данные именно там, где
они важнее всего.

ПРО ИНДИКАЦИЮ. Мигание встроенным светодиодом оставлено, но на платах
вроде RP2040-Zero вместо простого светодиода стоит адресный WS2812, и
мигания видно не будет. Это не поломка: код молча пропускает индикацию,
если ножку не удалось занять.

Заливка: положить файл на Pico под именем main.py после прошивки
MicroPython. Он запустится сам при подаче питания.
"""

import machine
import micropython
import struct
import sys
import time
from micropython import const

# ---------------------------------------------------------------------------
# Ножки и шина
# ---------------------------------------------------------------------------

I2C_BUS = 0
I2C_SDA_PIN = 0
I2C_SCL_PIN = 1
# 100 кГц безопасны для навесного монтажа без внешних подтяжек. MPU6050
# держит и 400 кГц, но на шлейфах это даёт пачки ETIMEDOUT — проверено на
# стенде, оттуда же и повторы в _i2c_retry ниже.
I2C_FREQ = 100_000

# ---------------------------------------------------------------------------
# Регистры MPU6050
# ---------------------------------------------------------------------------

MPU_ADDR = const(0x68)
REG_SMPLRT_DIV   = const(0x19)
REG_CONFIG       = const(0x1A)
REG_GYRO_CONFIG  = const(0x1B)
REG_ACCEL_CONFIG = const(0x1C)
REG_FIFO_EN      = const(0x23)
REG_INT_ENABLE   = const(0x38)
REG_USER_CTRL    = const(0x6A)
REG_PWR_MGMT_1   = const(0x6B)
REG_FIFO_COUNT_H = const(0x72)
REG_FIFO_R_W     = const(0x74)
REG_WHO_AM_I     = const(0x75)
REG_ACCEL_XOUT_H = const(0x3B)

# Биты FIFO_EN: 0x08 акселерометр, 0x70 три оси гироскопа.
FIFO_EN_MASK = const(0x78)
USER_CTRL_FIFO_EN  = const(0x40)
USER_CTRL_FIFO_RST = const(0x04)

# Выборка в FIFO: 6 байт акселерометра + 6 байт гироскопа.
SAMPLE_BYTES = const(12)

# Делитель частоты: при включённом ЦФНЧ базовая частота 1 кГц,
# 1000 / (1 + 4) = 200 Гц.
SMPLRT_DIV = const(4)

# Период дискретизации в микросекундах, он же шаг между соседними
# выборками в FIFO. Нужен, чтобы восстановить время каждой выборки по
# времени чтения пачки.
SAMPLE_US = const(5000)

# Шкалы. 0x08 в обоих регистрах: +-4 g и +-500 град/с.
ACCEL_FS_SEL = const(0x08)
GYRO_FS_SEL = const(0x08)

# Кадр: sync(2) seq(2) t_us(4) ax ay az gx gy gz (12) = 20 байт.
# Разбор на стороне ROS должен знать этот же формат, см. pico_imu_node.py.
FRAME_FMT = '<2sHI6h'
SYNC = b'\xAA\x55'

# ---------------------------------------------------------------------------


def _i2c_retry(fn, *args, _attempts=8, _delay_ms=5):
    """Повторяет операцию I2C при OSError.

    Навесной монтаж на GY-521 изредка роняет транзакцию. Короткий повтор
    восстанавливает обмен, тогда как исключение оборвало бы весь поток.
    """
    last_err = None
    for _ in range(_attempts):
        try:
            return fn(*args)
        except OSError as e:
            last_err = e
            time.sleep_ms(_delay_ms)
    raise last_err


def init_mpu(i2c):
    """Настраивает MPU6050 на выдачу акселерометра и гироскопа через FIFO."""
    # Пробный опрос. Многие клоны отвечают на WHO_AM_I не тем значением,
    # что в документации, но работают нормально, поэтому принимаем любой
    # ответ кроме явно битых 0x00 и 0xFF.
    who = _i2c_retry(i2c.readfrom_mem, MPU_ADDR, REG_WHO_AM_I, 1)[0]
    # Сообщаем, ЧТО за чип на самом деле. Подлинный MPU6050 отвечает 0x68;
    # всё прочее — клон, и у клонов раскладка битов диапазона бывает
    # сдвинута. Замерено на этой плате: регистр диапазона читается 0x08,
    # что по документации означает +-4 g и 8192 отсчёта на g, а тяжесть
    # выходит ровно вдвое меньше положенной. То есть чувствительность у
    # чипа 4096, как у +-8 g. Без этой строки причина была не видна.
    print('WHO_AM_I: 0x%02X%s' % (who, '' if who == 0x68
                                  else '  <-- не MPU6050, клон'))
    if who == 0xFF or who == 0x00:
        raise RuntimeError(
            'WHO_AM_I=0x%02X (похоже на обрыв или отсутствие подтяжек)' % who)

    def w(reg, val):
        _i2c_retry(i2c.writeto_mem, MPU_ADDR, reg, bytes((val,)))

    w(REG_PWR_MGMT_1, 0x80)          # сброс
    time.sleep_ms(100)
    # Тактирование от ФАПЧ по оси X гироскопа, а не от внутреннего
    # генератора: у внутреннего уход частоты заметно хуже, а метки времени
    # выборок нам нужны ровные.
    w(REG_PWR_MGMT_1, 0x01)
    time.sleep_ms(20)
    w(REG_CONFIG, 0x03)              # ЦФНЧ 3: полоса 44 Гц, базовые 1 кГц
    w(REG_SMPLRT_DIV, SMPLRT_DIV)
    # ДИАПАЗОНЫ ПРОВЕРЯЕМ ЧТЕНИЕМ, а не надеемся на запись.
    #
    # Замерено на живом стенде: неподвижный датчик отдавал тяжесть
    # 4.77 м/с² вместо 9.81, то есть РОВНО ВДВОЕ меньше. Узел делил на
    # 8192 отсчёта на g (это +-4 g, как здесь и написано), а чип на деле
    # отдавал по 4096, то есть стоял на +-8 g. Запись в регистр либо не
    # прошла, либо её кто-то перебил.
    #
    # Поэтому пишем, читаем обратно и повторяем, если не совпало. А затем
    # сообщаем фактическое значение: пусть хост видит правду, а не наши
    # намерения. Строка уходит до начала двоичного потока и разбору не
    # мешает — приёмник ищет метку синхронизации и мусор перед ней
    # пропускает.
    for reg, val, name in ((REG_ACCEL_CONFIG, ACCEL_FS_SEL, 'ACCEL'),
                           (REG_GYRO_CONFIG, GYRO_FS_SEL, 'GYRO')):
        got = None
        for _ in range(3):
            w(reg, val)
            time.sleep_ms(5)
            got = _i2c_retry(i2c.readfrom_mem, MPU_ADDR, reg, 1)[0]
            if got == val:
                break
        print('%s_CONFIG: записали 0x%02X, читается 0x%02X%s'
              % (name, val, got, '' if got == val else '  <-- НЕ ПРИНЯЛ'))
    w(REG_INT_ENABLE, 0x00)
    # FIFO НЕ ИСПОЛЬЗУЕМ. Почему — см. заголовок файла.
    w(REG_FIFO_EN, 0x00)
    w(REG_USER_CTRL, USER_CTRL_FIFO_RST)
    time.sleep_ms(2)


def _find_led():
    """Встроенный светодиод, если он вообще есть на этой плате."""
    for spec in ('LED', 'WL_GPIO0', 25):
        try:
            return machine.Pin(spec, machine.Pin.OUT)
        except (TypeError, ValueError, RuntimeError):
            continue
    return None


def stream():
    i2c = machine.I2C(I2C_BUS,
                      sda=machine.Pin(I2C_SDA_PIN),
                      scl=machine.Pin(I2C_SCL_PIN),
                      freq=I2C_FREQ)
    init_mpu(i2c)

    seq = 0
    out = sys.stdout.buffer.write
    # Горячий цикл: всё, что зовётся на каждой выборке, привязываем к
    # локальным именам — в MicroPython поиск по глобальным заметно дороже.
    pack = struct.pack
    fmt = FRAME_FMT
    sync = SYNC
    sleep_us = time.sleep_us
    ticks_us = time.ticks_us
    read_mem = i2c.readfrom_mem
    write_mem = i2c.writeto_mem

    led = _find_led()
    led_state = 0
    last_blink = ticks_us()

    next_us = ticks_us()
    while True:
        # Расписание по абсолютному времени, а не "поспать период": при
        # втором способе длительность самого чтения накапливается, и
        # частота уползает вниз.
        now = ticks_us()
        dt = next_us - now
        if dt > 0:
            sleep_us(dt if dt < SAMPLE_US else SAMPLE_US)
            continue
        next_us += SAMPLE_US
        # Если отстали больше чем на выборку (заминка USB), не нагоняем
        # пачкой, а выравниваем расписание по текущему моменту.
        if now - next_us > 5 * SAMPLE_US:
            next_us = now + SAMPLE_US

        try:
            # Акселерометр, температура и гироскоп лежат в регистрах
            # подряд с 0x3B. Читаем одним куском: два отдельных чтения
            # разошлись бы во времени на доли миллисекунды и дали бы
            # рассогласование угловой скорости с ускорением.
            d = read_mem(MPU_ADDR, REG_ACCEL_XOUT_H, 14)
        except OSError:
            time.sleep_ms(2)
            continue

        v = []
        for k in (0, 1, 2, 4, 5, 6):        # 3 — температура, пропускаем
            raw = (d[2 * k] << 8) | d[2 * k + 1]
            v.append(raw - 65536 if raw >= 32768 else raw)
        try:
            out(pack(fmt, sync, seq & 0xFFFF, now & 0xFFFFFFFF, *v))
        except Exception:
            # Хост закрыл порт или не успевает читать. Раньше это
            # исключение всплывало из stream() наружу, внешний цикл делал
            # пять попыток и сдавался — плата замолкала НАВСЕГДА, и
            # помогал только сброс. Снаружи выглядело как «датчик сгорел».
            # Выборку теряем, поток продолжаем.
            pass
        seq = (seq + 1) & 0xFFFF

        if led is not None and ticks_us() - last_blink > 250_000:
            led_state ^= 1
            led.value(led_state)
            last_blink = ticks_us()


if __name__ == '__main__':
    # Пауза на старте нужна по двум причинам: дать хосту опознать
    # устройство прежде, чем в него польётся двоичный поток, и оставить
    # окно, в которое успеваешь нажать Ctrl-C и попасть в REPL для
    # перепрошивки. Окно работает только ЗДЕСЬ, до kbd_intr ниже.
    time.sleep_ms(1500)
    # Перезапускаем БЕЗ ограничения числа попыток. Ограничение в пять
    # означало, что после нескольких отключений хоста плата умолкала до
    # ручного сброса, а по USB этого не видно — выглядит как отказ железа.
    # Единственный способ выйти отсюда — Ctrl-C, то есть осознанное
    # подключение человеком для перепрошивки.
    # ПРО Ctrl-C. Вот из-за чего плата «умирала».
    #
    # MicroPython считает байт 0x03 во входящем потоке командой прерывания
    # и возбуждает KeyboardInterrupt. Он наследуется не от Exception, а от
    # BaseException, и потому проходил СКВОЗЬ защиту внутри stream() и
    # сквозь except Exception ниже — прямо во внешний цикл, где стояло
    # «break». Плата умолкала навсегда, помогал только перетык питания.
    # Наблюдалось трижды за день, каждый раз после того, как хост закрывал
    # и открывал порт: закрытие порождает на линии состояние, которое
    # прошивка принимает за Ctrl-C.
    #
    # Первая попытка лечения — micropython.kbd_intr(-1), то есть отключить
    # трактовку вовсе, — оказалась перебором: вместе с бедой она отняла и
    # возможность перепрошить плату по порту, пока она работает. Пришлось
    # бы каждый раз снимать питание.
    #
    # Поэтому различаем случайность и намерение ПО ЧАСТОТЕ. Одиночное
    # прерывание — это закрытие порта, его проглатываем и продолжаем.
    # Три подряд меньше чем за секунду — это человек, который хочет в
    # REPL, и тогда выходим.
    hits = []

    while True:
        try:
            stream()
        except KeyboardInterrupt:
            now = time.ticks_ms()
            hits.append(now)
            del hits[:-3]
            if len(hits) == 3 and now - hits[0] < 1000:
                break
            time.sleep_ms(100)
        except Exception as _e:
            try:
                print('[stream] упал:', _e, '- повтор')
            except Exception:
                pass
            time.sleep_ms(500)
